/**
 * Reference-dependent image candidates (engine-independent guard). Real draft routes build the drafts; the identity and
 * status functions are the server's own. No image engine runs, and no provider is called.
 * Replacing a style or character reference, or changing its role, makes THIS draft's candidates stale. Other drafts and
 * drafts without references keep their candidates. Final shots and storyboard panels are not references.
 */
import fs from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';

vi.hoisted(() => {
  const nodeFs = process.getBuiltinModule('node:fs') as typeof import('node:fs');
  const nodePath = process.getBuiltinModule('node:path') as typeof import('node:path');
  const os = process.getBuiltinModule('node:os') as typeof import('node:os');
  const root = nodeFs.mkdtempSync(nodePath.join(os.tmpdir(), 'factory-refcand-'));
  process.env.BUILDTRAKE_DATA = nodePath.join(root, 'data');
  process.env.BUILDTRAKE_OUTPUT = nodePath.join(root, 'output');
  process.env.VF_PREVIEW_DISABLE = '1';
  return { root };
});

import { buildServerApp } from '../apps/api/src/server.js';
import { ASSETS_DIR, DATA_DIR } from '../apps/api/src/services/platform.js';
import { loadAssetIndex, saveAssetIndex } from '../apps/api/src/routes/assets.js';
import { candidateIdentityFor, candidateStatus } from '../apps/api/src/services/factory-service.js';

type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;
const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==', 'base64');

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({ method, url, payload: body === undefined ? undefined : JSON.stringify(body), headers: body === undefined ? {} : { 'content-type': 'application/json' } });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json };
}

function seedAsset(id: string, sha256: string | undefined) {
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  fs.writeFileSync(path.join(ASSETS_DIR, `${id}.png`), PNG);
  saveAssetIndex([...loadAssetIndex(), {
    id, name: `Fixture ${id}`, kind: 'screenshot', fileName: `${id}.png`, path: `${id}.png`, mimeType: 'image/png', sizeBytes: PNG.length,
    tags: [], status: 'active', preferred: false, source: 'Fixture (synthetic, generated by the test)', license: 'Test fixture',
    addedAt: new Date().toISOString(), usedIn: [], blocked: false, ...(sha256 ? { sha256 } : {}),
  } as never]);
}

/**
 * LABELLED TEST SETUP: the planner classifies a storyboard panel with no picture as a recording need, so a candidate
 * (an image shot) is not reachable through the routes alone. This sets only that one stored row to an image shot,
 * in the draft file the server reads. Nothing else in the draft is changed.
 */
function makeShotImageNeeded(draftId: string) {
  const file = path.join(DATA_DIR, 'factory', 'drafts', `${draftId}.json`);
  const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
  const row = doc.selection.find((x: any) => x.id === 'g1');
  if (!row) throw new Error('setup: shot g1 not found');
  delete row.shot;
  row.assetId = null;
  fs.writeFileSync(file, JSON.stringify(doc, null, 2));
}

/** A draft with one image-needed shot (a panel with no picture) and the given picture attached. */
async function draftWith(assetIds: string[]) {
  const r = await call('POST', '/api/factory/drafts', {
    contentProfile: 'educational', format: 'landscape', channelBrandId: null, requestedSpeakers: [], referenceProjectId: null, visualLanguage: null,
    inputs: {
      brief: '', script: null, audioAssetId: null, visualAssetIds: assetIds,
      storyboard: { version: 1, scenes: [{ id: 'g1', narration: 'A plain shot with no picture.', speakerId: null, assetId: null, startSec: null, endSec: null, locked: false }] },
    },
  });
  if (r.status !== 201) throw new Error(`draft setup failed: ${r.status} ${JSON.stringify(r.json)}`);
  makeShotImageNeeded(r.json.draftId);
  return r.json as { draftId: string; revision: number };
}

/** PATCH the draft's roles, then re-apply the labelled shot setup, because a PATCH re-plans the selection. */
async function patchRoles(draftId: string, expectedRevision: number, visualRoles: Record<string, string>) {
  const r = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, { expectedRevision, visualRoles });
  if (r.status === 200) makeShotImageNeeded(draftId);
  return r;
}

beforeAll(async () => {
  app = await buildServerApp();
  fs.mkdirSync(DATA_DIR, { recursive: true });
  seedAsset('ref-style', 'a'.repeat(64));
  seedAsset('ref-other', 'b'.repeat(64));
  seedAsset('pic-final', 'c'.repeat(64));
});
afterAll(async () => { await app?.close(); });

describe('reference-dependent image candidates', () => {
  it('a draft without references keeps its candidate fingerprint when another draft changes its reference', async () => {
    const plain = await draftWith(['pic-final']);
    const withRef = await draftWith(['ref-style']);
    await patchRoles(withRef.draftId, withRef.revision, { 'ref-style': 'style_reference' });
    const before = candidateIdentityFor(plain.draftId, 'g1').fingerprint;
    const role = await patchRoles(withRef.draftId, withRef.revision + 1, { 'ref-style': 'final_shot' });
    expect(role.status).toBe(200);
    expect(candidateIdentityFor(plain.draftId, 'g1').fingerprint).toBe(before);
  });

  it('changing a reference role makes that draft\'s candidate stale, and approve or bind is refused with the reason', async () => {
    const d = await draftWith(['ref-style']);
    const set = await patchRoles(d.draftId, d.revision, { 'ref-style': 'style_reference' });
    expect(set.status).toBe(200);
    const candidate = candidateIdentityFor(d.draftId, 'g1');
    const ref = { draftId: d.draftId, sceneId: 'g1', fingerprint: candidate.fingerprint };
    expect(candidateStatus(ref).current).toBe(true);
    const changed = await patchRoles(d.draftId, set.json.revision, { 'ref-style': 'character_reference' });
    expect(changed.status).toBe(200);
    const status = candidateStatus(ref);
    expect(status.current).toBe(false);
    expect(status.reason).toBe('prompt_changed');
  });

  it('replacing the reference picture makes that draft\'s candidate stale', async () => {
    // Both pictures are attached at Create. The swap moves the style role from one to the other.
    const d = await draftWith(['ref-style', 'ref-other']);
    await patchRoles(d.draftId, d.revision, { 'ref-style': 'style_reference' });
    const ref = { draftId: d.draftId, sceneId: 'g1', fingerprint: candidateIdentityFor(d.draftId, 'g1').fingerprint };
    const cur = await call('GET', `/api/factory/drafts/${d.draftId}`);
    const swap = await patchRoles(d.draftId, cur.json.revision, { 'ref-style': 'final_shot', 'ref-other': 'style_reference' });
    expect(swap.status).toBe(200);
    expect(candidateStatus(ref).current).toBe(false);
  });

  it('a final shot attached to a draft is not a reference and leaves the candidate unchanged', async () => {
    const d = await draftWith(['pic-final']);
    const before = candidateIdentityFor(d.draftId, 'g1').fingerprint;
    const cur = await call('GET', `/api/factory/drafts/${d.draftId}`);
    const r = await patchRoles(d.draftId, cur.json.revision, { 'pic-final': 'final_shot' });
    expect(r.status).toBe(200);
    expect(candidateIdentityFor(d.draftId, 'g1').fingerprint).toBe(before);
  });

  it('uploads store a SHA-256 of the stored bytes, the identity used for references', () => {
    const asset = loadAssetIndex().find((a) => a.id === 'ref-style');
    expect(asset?.sha256).toBe('a'.repeat(64));
  });
});
