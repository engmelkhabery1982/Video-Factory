/**
 * Phase 3 input path: supplied screen recording (video asset) with supplied narration.
 * Real HTTP routes, isolated data under .stills/test-isolation. The video is a synthetic
 * fixture file, not a screen recording of the owner's software. Code-level/HTTP evidence only.
 */
import fs from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';

const tmp = vi.hoisted(() => {
  const nodeFs = process.getBuiltinModule('node:fs') as typeof import('node:fs');
  const nodePath = process.getBuiltinModule('node:path') as typeof import('node:path');
  delete process.env.VF_ALIGN_COMMAND;
  process.env.VF_PREVIEW_DISABLE = '1';
  const root = nodePath.join(process.cwd(), '.stills', 'test-isolation', 'factory-video-narration');
  const data = nodePath.join(root, 'data');
  const output = nodePath.join(root, 'output');
  nodeFs.rmSync(root, { recursive: true, force: true });
  nodeFs.mkdirSync(data, { recursive: true });
  nodeFs.mkdirSync(output, { recursive: true });
  process.env.BUILDTRAKE_DATA = data;
  process.env.BUILDTRAKE_OUTPUT = output;
  return { root, data };
});

import { buildServerApp } from '../apps/api/src/server.js';
import { ASSETS_DIR } from '../apps/api/src/services/platform.js';
import { loadAssetIndex, saveAssetIndex } from '../apps/api/src/routes/assets.js';
import { readEditorState } from '../apps/api/src/services/editor-store.js';
import { createHash } from 'node:crypto';

type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;

function wavSilence(seconds: number): Buffer {
  const rate = 8000;
  const n = Math.round(seconds * rate);
  const data = Buffer.alloc(n * 2);
  const h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVE', 8);
  h.write('fmt ', 12); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22);
  h.writeUInt32LE(rate, 24); h.writeUInt32LE(rate * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34);
  h.write('data', 36); h.writeUInt32LE(data.length, 40);
  return Buffer.concat([h, data]);
}

async function call(method: 'GET' | 'POST', url: string, body?: unknown) {
  const res = await app.inject({
    method, url,
    payload: body === undefined ? undefined : JSON.stringify(body),
    headers: body === undefined ? {} : { 'content-type': 'application/json' },
  });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json };
}

beforeAll(async () => {
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  const video = Buffer.from('fixture video bytes, not a screen capture');
  fs.writeFileSync(path.join(ASSETS_DIR, 'fx-screen.mp4'), video);
  fs.writeFileSync(path.join(ASSETS_DIR, 'fx-narration-6s.wav'), wavSilence(6));
  const base = { tags: [], status: 'active', preferred: false, source: 'Fixture (synthetic, generated by the test)', license: 'Test fixture', addedAt: new Date().toISOString(), usedIn: [], blocked: false };
  saveAssetIndex([
    ...loadAssetIndex(),
    { ...base, id: 'fx-screen', name: 'Fixture screen capture', kind: 'broll', fileName: 'fx-screen.mp4', path: 'fx-screen.mp4', mimeType: 'video/mp4', sizeBytes: video.length, durationSec: 60 },
    { ...base, id: 'fx-narration-6s', name: 'Fixture narration 6s', kind: 'sfx', fileName: 'fx-narration-6s.wav', path: 'fx-narration-6s.wav', mimeType: 'audio/wav', sizeBytes: wavSilence(6).length, durationSec: 6 },
  ] as never);
  app = await buildServerApp();
  await app.ready();
});

afterAll(async () => {
  await app?.close();
});

describe('supplied screen recording with supplied narration', () => {
  it('reaches the same editable project: the video is the picture, the supplied audio is the narration, and nothing is generated', async () => {
    const storyboard = {
      version: 1,
      scenes: [
        { id: 'sv1', narration: 'Open the delivery board and read the confirmed window.', speakerId: 'learner', assetId: 'fx-screen', startSec: 0, endSec: 3, locked: false },
        { id: 'sv2', narration: 'Then write the window on the site board.', speakerId: 'instructor', assetId: 'fx-screen', startSec: 3, endSec: 6, locked: false },
      ],
    };
    const created = await call('POST', '/api/factory/drafts', {
      contentProfile: 'educational', format: 'landscape', channelBrandId: null,
      inputs: { brief: 'Screen walkthrough', script: null, audioAssetId: 'fx-narration-6s', visualAssetIds: [], storyboard },
      requestedSpeakers: [], referenceProjectId: null,
    });
    expect(created.status).toBe(201);
    expect(created.json.status).toBe('review_required');

    const applied = await call('POST', `/api/factory/drafts/${created.json.draftId}/apply`, { expectedRevision: 0 });
    expect(applied.status).toBe(201);
    const doc = readEditorState(applied.json.projectId, 'long')!.document;
    expect(doc.visualClips.every((c) => c.sourceAssetId === 'fx-screen')).toBe(true);
    expect(doc.visualClips.map((c) => [c.startSec, c.durationSec])).toEqual([[0, 3], [3, 3]]);
    expect(doc.audioClips.map((a) => a.id)).toEqual(['ac_full_narration']);
    expect(doc.alignment.audioSha256).toBe(createHash('sha256').update(wavSilence(6)).digest('hex'));
  });

  it('a video asset with no narration source is a visible gap: the draft is blocked and the apply refuses', async () => {
    const created = await call('POST', '/api/factory/drafts', {
      contentProfile: 'educational', format: 'landscape', channelBrandId: null,
      inputs: { brief: 'Screen only', script: null, audioAssetId: null, visualAssetIds: ['fx-screen'], storyboard: null },
      requestedSpeakers: [], referenceProjectId: null,
    });
    expect(created.status).toBe(201);
    expect(created.json.status).toBe('blocked');
    expect(created.json.missing.length).toBeGreaterThan(0);
    const applied = await call('POST', `/api/factory/drafts/${created.json.draftId}/apply`, { expectedRevision: created.json.revision });
    expect(applied.status).toBeGreaterThanOrEqual(400);
  });
});
