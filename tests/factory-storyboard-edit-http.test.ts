const draftBytes = (draftId: string): string => fs.readFileSync(path.join(DATA_DIR, 'factory', 'drafts', `${draftId}.json`), 'utf8');
const storyboardOf = (json: any) => json.intake.storyboard;
const patchStoryboard = (draftId: string, expectedRevision: number, scenes: any[], extra: Record<string, unknown> = {}) =>
  call('PATCH', `/api/factory/drafts/${draftId}/intake`, { expectedRevision, storyboard: { version: 1, scenes }, ...extra });

describe('post-create storyboard edits: refusals leave persisted bytes unchanged', () => {
  it('a locked panel refuses a change to its words, granular to that panel, with 423 and no write', async () => {
    const r = await createDraft({
      storyboard: { version: 1, scenes: [panel('L1', 'Locked words.', 'img-a', { locked: true }), panel('U1', 'Free words.', 'img-b')] },
      narrationMode: 'none',
    });
    const id = r.json.draftId;
    const before = draftBytes(id);
    const p = await patchStoryboard(id, r.json.revision, [panel('L1', 'Changed.', 'img-a', { locked: true }), panel('U1', 'Free edit.', 'img-b')]);
    expect(p.status).toBe(423);
    expect(p.json.code).toBe('FACTORY_SCENE_LOCKED');
    expect(p.json.sceneIds).toEqual(['L1']);
    expect(draftBytes(id)).toBe(before);
  });

  it('a locked panel refuses a timing change even when the timing change is confirmed', async () => {
    const r = await createDraft({
      storyboard: { version: 1, scenes: [panel('L2', 'Locked timing.', 'img-a', { locked: true, startSec: 0, endSec: 2 })] },
      narrationMode: 'none',
    });
    const before = draftBytes(r.json.draftId);
    const p = await patchStoryboard(r.json.draftId, r.json.revision, [panel('L2', 'Locked timing.', 'img-a', { locked: true, startSec: 0, endSec: 3 })], { confirmTiming: true });
    expect(p.status).toBe(423);
    expect(draftBytes(r.json.draftId)).toBe(before);
  });

  it('a reordered, added or removed scene is refused as a supplied-order change, with no write', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('o1', 'One.', 'img-a'), panel('o2', 'Two.', 'img-b')] }, narrationMode: 'none' });
    const before = draftBytes(r.json.draftId);
    const reordered = await patchStoryboard(r.json.draftId, r.json.revision, [panel('o2', 'Two.', 'img-b'), panel('o1', 'One.', 'img-a')]);
    expect(reordered.status).toBe(422);
    expect(reordered.json.code).toBe('FACTORY_SUPPLIED_ORDER_CHANGED');
    const added = await patchStoryboard(r.json.draftId, r.json.revision, [panel('o1', 'One.', 'img-a'), panel('o2', 'Two.', 'img-b'), panel('o3', 'Three.', 'img-a')]);
    expect(added.json.code).toBe('FACTORY_SUPPLIED_ORDER_CHANGED');
    expect(draftBytes(r.json.draftId)).toBe(before);
  });

  it('an invalid storyboard (overlapping timing, unsupported version, bad field) is refused in full with no write', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('t1', 'A.', 'img-a', { startSec: 0, endSec: 4 }), panel('t2', 'B.', 'img-b', { startSec: 4, endSec: 8 })] }, narrationMode: 'none' });
    const before = draftBytes(r.json.draftId);
    const overlap = await patchStoryboard(r.json.draftId, r.json.revision, [panel('t1', 'A.', 'img-a', { startSec: 0, endSec: 5 }), panel('t2', 'B.', 'img-b', { startSec: 4, endSec: 8 })], { confirmTiming: true });
    expect(overlap.status).toBe(422);
    expect(JSON.stringify(overlap.json)).toMatch(/overlap|starts before/i);
    const version = await call('PATCH', `/api/factory/drafts/${r.json.draftId}/intake`, { expectedRevision: r.json.revision, storyboard: { version: 2, scenes: [] } });
    expect(version.status).toBe(422);
    const badField = await patchStoryboard(r.json.draftId, r.json.revision, [panel('t1', 'A.', 'img-a', { startSec: 0, endSec: 4, locked: 'yes' }), panel('t2', 'B.', 'img-b', { startSec: 4, endSec: 8 })]);
    expect(badField.status).toBe(422);
    expect(draftBytes(r.json.draftId)).toBe(before);
  });

  it('a timing change without confirmation is refused; confirmed, it persists and the revision advances by one', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('T1', 'Timed one.', 'img-a', { startSec: 0, endSec: 4 }), panel('T2', 'Timed two.', 'img-b', { startSec: 4, endSec: 8 })] }, narrationMode: 'none' });
    const id = r.json.draftId;
    const next = [panel('T1', 'Timed one.', 'img-a', { startSec: 0, endSec: 3.5 }), panel('T2', 'Timed two.', 'img-b', { startSec: 3.5, endSec: 8 })];
    const refused = await patchStoryboard(id, r.json.revision, next);
    expect(refused.status).toBe(422);
    expect(refused.json.code).toBe('FACTORY_TIMING_CONFIRMATION_REQUIRED');
    expect(refused.json.sceneIds).toEqual(['T1', 'T2']);
    const ok = await patchStoryboard(id, r.json.revision, next, { confirmTiming: true });
    expect(ok.status).toBe(200);
    expect(ok.json.revision).toBe(r.json.revision + 1);
    expect(storyboardOf(ok.json).scenes.map((s: any) => [s.id, s.startSec, s.endSec])).toEqual([['T1', 0, 3.5], ['T2', 3.5, 8]]);
  });

  it('a stale revision returns 409 with the current revision, and the draft is not written', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('S1', 'Stale one.', 'img-a')] }, narrationMode: 'none' });
    const before = draftBytes(r.json.draftId);
    const p = await patchStoryboard(r.json.draftId, r.json.revision + 5, [panel('S1', 'Typed edit that must survive.', 'img-a')]);
    expect(p.status).toBe(409);
    expect(p.json.code).toBe('FACTORY_REVISION_CONFLICT');
    expect(p.json.currentRevision).toBe(r.json.revision);
    expect(draftBytes(r.json.draftId)).toBe(before);
  });
});

describe('post-create storyboard edits: text authority, persist and reopen, and applying a changed revision', () => {
  it('words that differ from the approved script need an explicit textAuthority; script authority refuses them', async () => {
    const r = await createDraft({ script: SCRIPT, storyboard: { version: 1, scenes: [panel('X1', 'Words in the script.', 'img-a')] }, visualAssetIds: ['img-a'] });
    if (r.status !== 201) throw new Error(`setup failed: ${JSON.stringify(r.json)}`);
    const id = r.json.draftId;
    const differing = [panel('X1', 'Brand new storyboard words.', 'img-a')];
    const before = draftBytes(id);
    const needChoice = await patchStoryboard(id, r.json.revision, differing);
    expect(needChoice.status).toBe(422);
    expect(needChoice.json.code).toBe('FACTORY_TEXT_CONFLICT');
    expect(needChoice.json.conflicts).toEqual([{ sceneId: 'X1', against: 'script' }]);
    expect(draftBytes(id)).toBe(before);
    const scriptWins = await patchStoryboard(id, r.json.revision, differing, { textAuthority: 'script' });
    expect(scriptWins.status).toBe(422);
    expect(scriptWins.json.code).toBe('FACTORY_APPROVED_TEXT_IMMUTABLE');
    expect(draftBytes(id)).toBe(before);
    const storyboardWins = await patchStoryboard(id, r.json.revision, differing, { textAuthority: 'storyboard' });
    expect(storyboardWins.status).toBe(200);
    expect(storyboardWins.json.invalidated.some((x: any) => /differ from the approved script/.test(x.reason))).toBe(true);
  });

  it('persist and reopen: the edited words, timing, speaker and lock are read back, and the IDs are kept', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('R1', 'Reopen one.', 'img-a'), panel('R2', 'Reopen two.', 'img-b')] }, narrationMode: 'none' });
    const id = r.json.draftId;
    const next = [panel('R1', 'Reopen one, edited.', 'img-a', { startSec: 0, endSec: 2, locked: true }), panel('R2', 'Reopen two.', 'img-b', { startSec: 2, endSec: 5 })];
    const p = await patchStoryboard(id, r.json.revision, next, { confirmTiming: true });
    expect(p.status).toBe(200);
    const reopened = await call('GET', `/api/factory/drafts/${id}`);
    expect(reopened.status).toBe(200);
    expect(storyboardOf(reopened.json).scenes).toEqual(next.map((x) => ({ ...x, speakerId: null })));
    expect(reopened.json.revision).toBe(p.json.revision);
  });

  it('a changed draft applies to a new project, and the revision the apply checks is the current one', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('A1', 'Apply one.', 'img-a'), panel('A2', 'Apply two.', 'img-b')] }, narrationMode: 'none', captions: false });
    const id = r.json.draftId;
    const p = await patchStoryboard(id, r.json.revision, [panel('A1', 'Apply one, changed.', 'img-a'), panel('A2', 'Apply two.', 'img-b')]);
    expect(p.status).toBe(200);
    const applied = await call('POST', `/api/factory/drafts/${id}/apply`, { expectedRevision: p.json.revision, confirmSpeechCalls: 0 });
    expect(applied.status).toBe(201);
    expect(applied.json.speechGenerated).toBe(0);
  });
});
