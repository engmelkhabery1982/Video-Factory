async function waitForTranscription(jobId: string): Promise<any> {
  for (let i = 0; i < 600; i++) {
    const r = await call('GET', `/api/factory/transcriptions/${jobId}`);
    if (r.json.status !== 'running' && r.json.status !== 'queued') return r.json;
    await new Promise((res) => setTimeout(res, 20));
  }
  throw new Error('transcription did not finish');
}

