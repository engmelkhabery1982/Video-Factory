/** Scene rows live under the selected treatment. A missing treatment fails loudly; it is never defaulted to []. */
function scenesOf(json: any): any[] {
  const t = (json.treatments as any[]).find((x) => x.id === json.selectedTreatmentId);
  if (!t) throw new Error('the draft has no selected treatment');
  return t.scenes;
}
