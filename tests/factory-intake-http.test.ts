/**
 * Optional-input contract through the REAL routes (app.inject). No browser, no provider.
 *
 * Labelled doubles:
 *  - The Gemini fetch is a test double that FAILS the test if any provider URL is requested. The silent, supplied
 *    audio and transcription flows must make zero provider calls.
 *  - The transcription runner is tests/fixtures/transcription-runner-fixture.mjs: a FIXTURE that exercises the job
 *    contract. Its output is never presented as real transcription.
 * Evidence here is HTTP-only fixture evidence. It is not browser evidence and not owner-media evidence.
 */
