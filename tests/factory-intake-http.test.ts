describe('input matrix through the routes', () => {
  it('idea only: 201 blocked with a required script gap, no treatments, and the queue says what to supply', async () => {
    const r = await createDraft({ brief: 'Explain a topic' });
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('blocked');
    expect(r.json.missing.map((m: any) => m.kind)).toEqual(['script']);
    expect(r.json.completion[0]).toMatchObject({ kind: 'script', required: true });
  });

  it('images only, silent: 201 review_required with one shot per picture, no speaker, and no provider call', async () => {
    const r = await createDraft({ visualAssetIds: ['img-a', 'img-b'], narrationMode: 'none' });
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('review_required');
    expect(scenesOf(r.json).map((s: any) => s.assetId)).toEqual(['img-a', 'img-b']);
    expect(scenesOf(r.json).every((s: any) => s.speakerId === null && s.narration === '')).toBe(true);
    expect(providerCalls.n).toBe(0);
  });

  it('images only without narration none: blocked, and the reason says to choose silent', async () => {
    const r = await createDraft({ visualAssetIds: ['img-a'] });
    expect(r.json.status).toBe('blocked');
    expect(r.json.missing[0].reason).toMatch(/narration set to none/);
  });

  it('text storyboard with a silent panel and an image storyboard: order kept, pictures kept', async () => {
    const sb = { version: 1, scenes: [panel('p1', 'Panel one words.', 'img-a'), panel('p2', '', 'img-b')] };
    const r = await createDraft({ storyboard: sb, narrationMode: 'none' });
    expect(r.json.status).toBe('review_required');
    expect(scenesOf(r.json).map((s: any) => [s.id, s.assetId])).toEqual([['p1', 'img-a'], ['p2', 'img-b']]);
  });

  it('audio only: blocked on the audio text; the audio is never presented as a transcript', async () => {
    const r = await createDraft({ audioAssetId: 'aud-1' });
    expect(r.json.status).toBe('blocked');
    expect(r.json.missing.map((m: any) => m.kind)).toEqual(['transcription']);
  });

  it('script plus picture plus supplied audio: no speech is needed and no provider is called on create', async () => {
    const r = await createDraft({ script: SCRIPT, audioAssetId: 'aud-1', visualAssetIds: ['img-a'], narrationMode: 'supplied' });
    expect(r.status).toBe(201);
    expect(r.json.missing.some((m: any) => m.kind === 'speech')).toBe(false);
    expect(providerCalls.n).toBe(0);
  });

  it('audio attached with narration none is a conflict, and Apply refuses it', async () => {
    const r = await createDraft({ script: SCRIPT, audioAssetId: 'aud-1', narrationMode: 'none', visualAssetIds: ['img-a'] });
    expect(r.json.status).toBe('blocked');
    expect(r.json.missing.some((m: any) => m.kind === 'conflict')).toBe(true);
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision });
    expect(a.status).toBe(422);
  });
});

describe('conflict resolution, revisions and failed writes', () => {
  let draftId = '';
  let revision = 0;

  beforeAll(async () => {
    const sb = { version: 1, scenes: [panel('s1', 'Other words.', 'img-a'), panel('s2', 'More other words.', 'img-b')] };
    const r = await createDraft({ script: SCRIPT, storyboard: sb, visualAssetIds: ['img-a', 'img-b'] });
    expect(r.json.status).toBe('blocked');
    expect(r.json.textConflict.sources.map((x: any) => x.source).sort()).toEqual(['script', 'storyboard']);
    draftId = r.json.draftId;
    revision = r.json.revision;
  });

  it('Apply refuses an unresolved conflict and creates no project', async () => {
    const a = await call('POST', `/api/factory/drafts/${draftId}/apply`, { expectedRevision: revision });
    expect(a.status).toBe(422);
    expect(a.json.missing.some((m: any) => m.kind === 'conflict')).toBe(true);
  });

  it('a stale revision is refused with 409 and the current revision, and nothing changes', async () => {
    const before = await call('GET', `/api/factory/drafts/${draftId}`);
    const r = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, { expectedRevision: revision + 7, textAuthority: 'script' });
    expect(r.status).toBe(409);
    expect(r.json.currentRevision).toBe(revision);
    const after = await call('GET', `/api/factory/drafts/${draftId}`);
    expect(after.json.revision).toBe(before.json.revision);
    expect(after.json.textConflict).toEqual(before.json.textConflict);
  });

  it('an invalid authority is refused with 422 and the saved draft is preserved byte for byte', async () => {
    const before = await call('GET', `/api/factory/drafts/${draftId}`);
    const r = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, { expectedRevision: revision, textAuthority: 'guess' });
    expect(r.status).toBe(422);
    const after = await call('GET', `/api/factory/drafts/${draftId}`);
    expect(JSON.stringify(after.json)).toBe(JSON.stringify(before.json));
  });

  it('choosing the storyboard as authority is a revision-checked write; the storyboard panels become the shots', async () => {
    const r = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, { expectedRevision: revision, textAuthority: 'storyboard' });
    expect(r.status).toBe(200);
    expect(r.json.revision).toBe(revision + 1);
    expect(r.json.status).toBe('review_required');
    expect(scenesOf(r.json).map((s: any) => s.narration)).toEqual(['Other words.', 'More other words.']);
    revision = r.json.revision;
  });

  it('a stale second choice is refused: 409, and the owner sees the newer revision', async () => {
    const r = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, { expectedRevision: revision - 1, textAuthority: 'script' });
    expect(r.status).toBe(409);
  });
});

describe('source changes invalidate only the dependent results', () => {
  it('removing one supplied picture drops its role and note, lists it, and keeps the other picture', async () => {
    const r = await createDraft({ visualAssetIds: ['img-a', 'img-b'], narrationMode: 'none', visualRoles: { 'img-b': 'final_shot' }, visualNotes: { 'img-b': 'keep this framing' } });
    const p = await call('PATCH', `/api/factory/drafts/${r.json.draftId}/intake`, { expectedRevision: r.json.revision, visualAssetIds: ['img-a'] });
    expect(p.status).toBe(200);
    expect(p.json.invalidated.some((x: any) => /img-b/.test(x.reason))).toBe(true);
    expect(p.json.intake.visualRoles['img-b']).toBeUndefined();
    expect(scenesOf(p.json).map((s: any) => s.assetId)).toEqual(['img-a']);
  });

  it('a locked scene refuses an intake change with 423, and nothing is replaced', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('L1', 'Locked words.', 'img-a', { locked: true })] }, narrationMode: 'none' });
    const p = await call('PATCH', `/api/factory/drafts/${r.json.draftId}/intake`, { expectedRevision: r.json.revision, narrationMode: 'generate' });
    expect(p.status).toBe(423);
    const after = await call('GET', `/api/factory/drafts/${r.json.draftId}`);
    expect(after.json.revision).toBe(r.json.revision);
  });
});

describe('silent video exports with zero audio: Apply, the editor document and the timing', () => {
  it('a silent storyboard applies with zero speech calls, a labelled visual-duration proposal, and zero audio clips', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('v1', '', 'img-a'), panel('v2', '', 'img-b')] }, narrationMode: 'none', captions: false });
    expect(r.json.status).toBe('review_required');
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    expect(a.json.speechGenerated).toBe(0);
    expect(a.json.timingSource).toBe('visual_duration_proposal');
    const state = readEditorState(a.json.projectId, 'long');
    expect(state?.document.audioClips.length).toBe(0);
    expect(state?.document.captions?.length ?? 0).toBe(0);
    expect(providerCalls.n).toBe(0);
  });

  it('the same silent draft applied twice returns the same project (idempotent Apply)', async () => {
    const r = await createDraft({ storyboard: { version: 1, scenes: [panel('i1', '', 'img-a')] }, narrationMode: 'none' });
    const [x, y] = await Promise.all([
      call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision }),
      call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision }),
    ]);
    expect(x.json.projectId).toBe(y.json.projectId);
    expect([x.status, y.status].sort()).toEqual([200, 201]);
    const again = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision });
    expect(again.status).toBe(200);
    expect(again.json.projectId).toBe(x.json.projectId);
  });

  it('supplied audio with a script applies with zero speech calls and never routes to synthesis', async () => {
    const r = await createDraft({ script: SCRIPT, audioAssetId: 'aud-2', visualAssetIds: ['img-a'], narrationMode: 'supplied' });
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    expect(a.json.speechGenerated).toBe(0);
    expect(providerCalls.n).toBe(0);
  });
});

describe('transcription jobs: status, cancel, review, stale and failure', () => {
  it('without a configured runner: the job is recorded as unavailable with the exact reason; nothing runs', async () => {
    const r = await call('POST', '/api/factory/transcriptions', { audioAssetId: 'aud-1' });
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('unavailable');
    expect(r.json.reason).toMatch(/VF_TRANSCRIBE_COMMAND/);
    const c = await call('POST', `/api/factory/transcriptions/${r.json.jobId}/cancel`);
    expect(c.status).toBe(409);
    expect(c.json.code).toBe('FACTORY_TRANSCRIPTION_NOT_RUNNING');
    const rev = await call('PATCH', `/api/factory/transcriptions/${r.json.jobId}`, { text: 'x', expectedRevision: r.json.revision });
    expect(rev.status).toBe(422);
    expect(rev.json.code).toBe('FACTORY_TRANSCRIPTION_NOT_READY');
    expect(providerCalls.n).toBe(0);
  });

  it('a runner that fails: failed, no transcript, review refused, and the draft gap remains', async () => {
    process.env.VF_TRANSCRIBE_COMMAND = JSON.stringify(['node', RUNNER]);
    process.env.FIXTURE_RUNNER_MODE = 'fail';
    const started = await call('POST', '/api/factory/transcriptions', { audioAssetId: 'aud-1' });
    const job = await waitForTranscription(started.json.jobId);
    expect(job.status).toBe('failed');
    expect(job.transcript).toBeNull();
    const rev = await call('PATCH', `/api/factory/transcriptions/${job.jobId}`, { text: 'x', expectedRevision: job.revision });
    expect(rev.status).toBe(422);
  });

  it('a successful fixture run: succeeded, labelled FIXTURE, review revision-checked, then planning uses the reviewed text', async () => {
    process.env.VF_TRANSCRIBE_COMMAND = JSON.stringify(['node', RUNNER]);
    const started = await call('POST', '/api/factory/transcriptions', { audioAssetId: 'aud-1' });
    expect(started.status).toBe(201);
    const job = await waitForTranscription(started.json.jobId);
    expect(job.status).toBe('succeeded');
    expect(job.provenance.fixture).toBe(true);
    expect(job.provenance.independentOfScript).toBe(true);
    expect(job.reason).toMatch(/FIXTURE/);
    expect(job.progress).toBe(1);

    const stale = await call('PATCH', `/api/factory/transcriptions/${job.jobId}`, { text: 'Reviewed.', expectedRevision: job.revision + 9 });
    expect(stale.status).toBe(409);
    const reviewed = await call('PATCH', `/api/factory/transcriptions/${job.jobId}`, { text: 'Reviewed line one.\n\nReviewed line two.', expectedRevision: job.revision });
    expect(reviewed.status).toBe(200);
    expect(reviewed.json.reviewedText).toBe('Reviewed line one.\n\nReviewed line two.');

    const d = await createDraft({ audioAssetId: 'aud-1', transcriptJobId: job.jobId, visualAssetIds: ['img-a'] });
    expect(d.json.missing.some((m: any) => m.kind === 'transcription')).toBe(false);
    expect(scenesOf(d.json).map((s: any) => s.narration)).toEqual(['Reviewed line one.', 'Reviewed line two.']);
    expect(providerCalls.n).toBe(0);
  });

  it('a transcript of other audio is stale: never used, the gap returns, and the warning says why', async () => {
    process.env.VF_TRANSCRIBE_COMMAND = JSON.stringify(['node', RUNNER]);
    const started = await call('POST', '/api/factory/transcriptions', { audioAssetId: 'aud-1' });
    const job = await waitForTranscription(started.json.jobId);
    await call('PATCH', `/api/factory/transcriptions/${job.jobId}`, { text: 'Reviewed for the first audio.', expectedRevision: job.revision });
    const d = await createDraft({ audioAssetId: 'aud-2', transcriptJobId: job.jobId, visualAssetIds: ['img-a'] });
    expect(d.json.missing.some((m: any) => m.kind === 'transcription')).toBe(true);
    expect(d.json.warnings.join(' ')).toMatch(/different audio/);
  });

  it('cancel: the job is canceled, and a late answer from a runner that ignores the stop never replaces the state', async () => {
    process.env.VF_TRANSCRIBE_COMMAND = JSON.stringify(['node', RUNNER]);
    process.env.FIXTURE_DELAY_MS = '600';
    process.env.FIXTURE_IGNORE_TERM = '1';
    const started = await call('POST', '/api/factory/transcriptions', { audioAssetId: 'aud-2' });
    expect(['queued', 'running']).toContain(started.json.status);
    const dup = await call('POST', '/api/factory/transcriptions', { audioAssetId: 'aud-2' });
    expect(dup.status).toBe(200);
    expect(dup.json.jobId).toBe(started.json.jobId);
    const canceled = await call('POST', `/api/factory/transcriptions/${started.json.jobId}/cancel`);
    expect(canceled.status).toBe(200);
    expect(canceled.json.status).toBe('canceled');
    await new Promise((res) => setTimeout(res, 1500));
    const later = await call('GET', `/api/factory/transcriptions/${started.json.jobId}`);
    expect(later.json.status).toBe('canceled');
    expect(later.json.transcript).toBeNull();
    expect(later.json.reviewedText).toBeNull();
  });

  it('restart: a job left running by a previous process is marked interrupted, with no result assumed', async () => {
    const jobId = 'trs_0123456789abcdef';
    fs.mkdirSync(path.join(DATA_DIR, 'factory', 'transcripts'), { recursive: true });
    const stamp = new Date().toISOString();
    fs.writeFileSync(path.join(DATA_DIR, 'factory', 'transcripts', `${jobId}.json`), JSON.stringify({
      schemaVersion: 1, jobId, audioAssetId: 'aud-1', audioSha256: 'x'.repeat(64), audioDurationSec: 2, status: 'running',
      progress: 0.4, reason: null, createdAt: stamp, updatedAt: stamp, transcript: null, provenance: null, reviewedText: null, reviewedAt: null, revision: 3,
    }));
    const r = await call('GET', `/api/factory/transcriptions/${jobId}`);
    expect(r.json.status).toBe('interrupted');
    expect(r.json.transcript).toBeNull();
    expect(r.json.reason).toMatch(/No transcript was assumed/);
  });

  it('an unknown job id is 404 and a malformed one never reads a file', async () => {
    const r = await call('GET', '/api/factory/transcriptions/trs_ffffffffffffffff');
    expect(r.status).toBe(404);
    const bad = await call('GET', '/api/factory/transcriptions/..%2Fsecret');
    expect(bad.status).toBe(404);
  });
});
