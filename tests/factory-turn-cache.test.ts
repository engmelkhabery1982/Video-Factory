async function waitForJob(jobId: string): Promise<any> {
  for (let i = 0; i < 400; i++) {
    const r = await call('GET', `/api/factory/ai/jobs/${jobId}`);
    if (r.json.job.status !== 'running') return r.json.job;
    await new Promise((res) => setTimeout(res, 10));
  }
  throw new Error('job did not finish');
}

/** Hook on the CURRENT module instance (a restart creates a new one). */
async function setStageHook(fn: ((stage: string) => void) | null) {
  const mod = await import('../apps/api/src/services/factory-service.js');
  mod.factoryTestHooks.onStage = fn;
}

const projectCount = () => (fs.existsSync(PROJECTS_DIR) ? fs.readdirSync(PROJECTS_DIR).length : 0);
const speechAssetCount = () => loadAssetIndex().filter((a: any) => a.id.startsWith('factory-speech-')).length;
const production = async () => (await call('GET', '/api/factory/ai/status')).json.budget.used.production as number;

const ids: { draftId: string; firstSceneId: string; secondSceneId: string; applied: string } = { draftId: '', firstSceneId: '', secondSceneId: '', applied: '' };

