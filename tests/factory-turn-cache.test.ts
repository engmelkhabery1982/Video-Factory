describe('Partial apply: retry never pays twice for a validated turn (labelled provider double)', () => {
  it('builds a generated draft with three speech lines bound to library images', async () => {
    const plan = await call('POST', '/api/factory/ai/plans', { profile: 'educational', format: 'landscape', brief: 'Confirm the delivery window the night before.' });
    expect(plan.status).toBe(202);
    const job = await waitForJob(plan.json.job.id);
    expect(job.status).toBe('succeeded');
    const draft = await call('POST', `/api/factory/ai/plans/${job.id}/draft`, { format: 'landscape' });
    expect(draft.status).toBe(201);
    ids.draftId = draft.json.draftId;
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const t1 = d.json.treatments.find((t: any) => t.id === 'T1');
    // Recording needs are bound to a video; a still would be refused by the binding rule.
    const scenes = t1.scenes.map((s: any, i: number) => ({
      ...s,
      assetId: s.shot?.assetNeed === 'screen_recording_needed' ? 'fx-turn-video' : i % 2 === 0 ? 'fx-turn-a' : 'fx-turn-b',
    }));
    ids.firstSceneId = scenes[0].id;
    ids.secondSceneId = scenes[1].id;
    const patched = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, { expectedRevision: d.json.revision, selectedTreatmentId: 'T1', scenes, speakers: [] });
    expect(patched.status, patched.raw).toBe(200);
    expect(patched.json.status).toBe('review_required');
  });

  it('the apply preview is read-only: it reports three speech calls and calls no provider', async () => {
    const before = provider.tts;
    const p = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(p.status).toBe(200);
    expect(p.json.canApply).toBe(true);
    expect(p.json.speechCalls).toBe(3);
    expect(p.json.budget.remaining).toBe(10 - (await production()));
    expect(provider.tts).toBe(before);
  });

  it('forced failure after the FIRST validated turn: one call spent, one turn saved, nothing published', async () => {
    const usedBefore = await production();
    const projectsBefore = projectCount();
    const assetsBefore = speechAssetCount();
    await setStageHook((stage) => {
      if (stage === `after-turn:${ids.firstSceneId}`) throw new Error('forced failure after the first turn');
    });
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: (await call('GET', `/api/factory/drafts/${ids.draftId}`)).json.revision, confirmSpeechCalls: 3 });
    await setStageHook(null);
    expect(r.status).toBe(500);
    expect(provider.tts).toBeGreaterThanOrEqual(1);
    expect(await production()).toBe(usedBefore + 1);
    expect(projectCount()).toBe(projectsBefore);
    expect(speechAssetCount()).toBe(assetsBefore);
    expect(storedTurnCount()).toBe(1);
  });

  it('simulated restart: the saved turn and the ledger survive, and the preview needs two calls', async () => {
    await app.close();
    vi.resetModules();
    const server2 = await import('../apps/api/src/server.js');
    app = await server2.buildServerApp();
    const p = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(p.status).toBe(200);
    expect(p.json.speechCalls).toBe(2);
    expect(p.json.sceneIds).not.toContain(ids.firstSceneId);
    expect(storedTurnCount()).toBe(1);
  });

  it('a provider 401 during the retry counts as an attempt, publishes nothing, and keeps the saved turn', async () => {
    const usedBefore = await production();
    const ttsBefore = provider.tts;
    provider.failNextTts = 1;
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 2 });
    expect(r.status).toBe(401);
    expect(provider.tts - ttsBefore).toBe(1);
    expect(await production()).toBe(usedBefore + 1);
    expect(storedTurnCount()).toBe(1);
  });

  it('retry after the 401: the saved turn is reused and only the two missing turns are requested', async () => {
    const usedBefore = await production();
    const ttsBefore = provider.tts;
    const projectsBefore = projectCount();
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 2 });
    expect(r.status, r.raw).toBe(201);
    ids.applied = r.json.projectId;
    expect(provider.tts - ttsBefore).toBe(2);
    expect(await production()).toBe(usedBefore + 2);
    expect(projectCount()).toBe(projectsBefore + 1);
    expect(r.json.speechGenerated).toBe(3);
  });

  it('concurrent duplicate applies produce exactly one project and make no provider call', async () => {
    const ttsBefore = provider.tts;
    const projectsBefore = projectCount();
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const body = { expectedRevision: d.json.revision, confirmSpeechCalls: 0 };
    const [a, b] = await Promise.all([
      call('POST', `/api/factory/drafts/${ids.draftId}/apply`, body),
      call('POST', `/api/factory/drafts/${ids.draftId}/apply`, body),
    ]);
    expect([a.status, b.status].sort()).toEqual([200, 200]);
    expect(a.json.projectId).toBe(ids.applied);
    expect(b.json.projectId).toBe(ids.applied);
    expect(a.json.reused).toBe(true);
    expect(provider.tts).toBe(ttsBefore);
    expect(projectCount()).toBe(projectsBefore);
  });

  it('labelled doubles never write verification evidence: the fixture record is unchanged', () => {
    const file = path.join(DATA_DIR, 'factory', 'ai', 'verification.json');
    const record = JSON.parse(fs.readFileSync(file, 'utf8'));
    expect(record.checkedAt).toBe('FIXTURE-2026-10-13');
    expect(record.endpoint.startsWith('FIXTURE')).toBe(true);
  });
});
