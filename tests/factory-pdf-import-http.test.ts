class PdfBuilder {
  private objects = new Map<number, string | Buffer>();
  set(id: number, body: string | Buffer): this {
    this.objects.set(id, body);
    return this;
  }

  build(rootId = 1, extraTrailer = ''): Buffer {
    const ids = [...this.objects.keys()].sort((a, b) => a - b);
    let out = '%PDF-1.4\n';
    const offsets = new Map<number, number>();
    for (const id of ids) {
      offsets.set(id, Buffer.byteLength(out, 'latin1'));
      const body = this.objects.get(id) as string | Buffer;
      out += `${id} 0 obj\n`;
      if (Buffer.isBuffer(body)) {
        out = Buffer.concat([Buffer.from(out, 'latin1'), body, Buffer.from('\nendobj\n', 'latin1')]);
      } else {
        out += `${body}\nendobj\n`;
      }
    }
    const xrefStart = Buffer.byteLength(out, 'latin1');
    out += `xref\n0 ${ids.length + 1}\n0000000000 65535 f \n`;
    for (const id of ids) out += `${String(offsets.get(id)).padStart(10, '0')} 00000 n \n`;
    out += `trailer\n<< /Size ${ids.length + 1} /Root ${rootId} 0 R${extraTrailer} >>\nstartxref\n${xrefStart}\n%%EOF\n`;
    return Buffer.from(out, 'latin1');
  }
}

const streamObj = (dict: string, bytes: Buffer): string =>
  `${dict}\nstream\n` + bytes.toString('latin1') + '\nendstream';

function textPage(builder: PdfBuilder, pageId: number, contentId: number, parentId: number, text: string, extraResources = ''): void {
  const content = Buffer.from(`BT /F1 12 Tf 72 700 Td (${text}) Tj ET`, 'latin1');
  builder.set(contentId, streamObj(`<< /Length ${content.length} >>`, content));
  builder.set(
    pageId,
    `<< /Type /Page /Parent ${parentId} 0 R /Resources << /Font << /F1 10 0 R >>${extraResources} >> /Contents ${contentId} 0 R >>`,
  );
}

function multipart(fileName: string, content: Buffer, fields: Record<string, string>) {
  const boundary = '----arenaPdfImport';
  const parts: Buffer[] = [];
  for (const [name, value] of Object.entries(fields)) {
    parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="${name}"\r\n\r\n${value}\r\n`));
  }
  parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="${fileName}"\r\nContent-Type: application/pdf\r\n\r\n`));
  parts.push(content);
  parts.push(Buffer.from(`\r\n--${boundary}--\r\n`));
  return { headers: { 'content-type': `multipart/form-data; boundary=${boundary}` }, payload: Buffer.concat(parts) };
}

const SOURCE = 'Synthetic PDF fixture (generated by the test)';
const LICENSE = 'Synthetic fixture, test only';

async function importPdf(pdf: Buffer, fields: Record<string, string> = { source: SOURCE, license: LICENSE }) {
  const res = await app.inject({
    method: 'POST',
    url: '/api/factory/imports/storyboard-pdf',
    ...multipart('storyboard.pdf', pdf, fields),
  });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json };
}

