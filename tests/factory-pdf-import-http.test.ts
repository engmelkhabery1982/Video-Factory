async function twoPagePdfWithJpeg(secondPicture = false, override?: Buffer): Promise<Buffer> {
  const jpeg = override ?? await sharp({ create: { width: 12, height: 8, channels: 3, background: '#336699' } }).jpeg().toBuffer();
  const b = new PdfBuilder();
  b.set(1, '<< /Type /Catalog /Pages 2 0 R >>');
  b.set(2, '<< /Type /Pages /Kids [3 0 R 5 0 R] /Count 2 >>');
  textPage(b, 3, 4, 2, 'First panel words', ' /XObject << /Im1 9 0 R >>');
  textPage(b, 5, 6, 2, 'Second panel words', secondPicture ? ' /XObject << /Im1 9 0 R >>' : '');
  b.set(10, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  b.set(
    9,
    `<< /Type /XObject /Subtype /Image /Width 12 /Height 8 /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${jpeg.length} >>\nstream\n` +
      jpeg.toString('latin1') +
      '\nendstream',
  );
  return b.build();
}

describe('POST /api/factory/imports/storyboard-pdf', () => {
  it('refuses truncated JPEG bytes without touching files or the index', async () => {
    const before = fs.readdirSync(ASSETS_DIR).sort();
    const index = fs.readFileSync(path.join(ASSETS_DIR, 'index.json'));
    const r = await importPdf(await twoPagePdfWithJpeg(false, Buffer.from([255, 216, 255, 224, 0, 16, 1, 2])));
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_PDF_UNSUPPORTED');
    expect(fs.readdirSync(ASSETS_DIR).sort()).toEqual(before);
    expect(fs.readFileSync(path.join(ASSETS_DIR, 'index.json'))).toEqual(index);
  });

  it('rolls back earlier images and a partial later write, preserving the existing index', async () => {
    const pdf = await twoPagePdfWithJpeg(true);
    const before = fs.readdirSync(ASSETS_DIR).sort();
    const index = fs.readFileSync(path.join(ASSETS_DIR, 'index.json'));
    const original = fs.writeFileSync;
    let writes = 0;
    const spy = vi.spyOn(fs, 'writeFileSync').mockImplementation(((file: any, bytes: any, options: any) => {
      if (typeof file === 'number' && ++writes === 2) {
        original(file, Buffer.from([255, 216]));
        throw new Error('LABELLED injected partial second-image write failure');
      }
      return original(file, bytes, options);
    }) as typeof fs.writeFileSync);
    let r: Awaited<ReturnType<typeof importPdf>>;
    try { r = await importPdf(pdf); } finally { spy.mockRestore(); }
    expect(writes).toBe(2);
    expect(r!.status).toBe(500);
    expect(fs.readdirSync(ASSETS_DIR).sort()).toEqual(before);
    expect(fs.readFileSync(path.join(ASSETS_DIR, 'index.json'))).toEqual(index);
  });

  it('imports pages in exact order, binds the JPEG to its page, and records source/licence on the asset', async () => {
    const r = await importPdf(await twoPagePdfWithJpeg());
    expect(r.status).toBe(201);
    expect(r.json.parser).toBe('builtin-pdf-storyboard-parser-v1');
    expect(r.json.report.pageCount).toBe(2);
    expect(r.json.storyboard.version).toBe(1);
    expect(r.json.storyboard.scenes.map((s: any) => s.id)).toEqual(['page-01', 'page-02']);
    expect(r.json.storyboard.scenes.map((s: any) => s.narration)).toEqual(['First panel words', 'Second panel words']);
    // Locks, speakers and times are never invented at import.
    expect(r.json.storyboard.scenes.every((s: any) => s.locked === false && s.speakerId === null && s.startSec === null && s.endSec === null)).toBe(true);

    expect(r.json.visualAssetIds).toHaveLength(1);
    const pictureId = r.json.storyboard.scenes[0].assetId;
    expect(pictureId).toBe(r.json.visualAssetIds[0]);
    expect(r.json.storyboard.scenes[1].assetId).toBeNull();

    const stored = loadAssetIndex().find((a) => a.id === pictureId);
    expect(stored).toBeTruthy();
    expect(stored!.mimeType).toBe('image/jpeg');
    expect(stored!.source).toBe(SOURCE);
    expect(stored!.license).toBe(LICENSE);
    expect(stored!.tags).toContain('pdf-import');
    expect(stored!.sha256).toMatch(/^[0-9a-f]{64}$/);
    expect(providerCalls.n).toBe(0);
  });

  it('rolls back pictures and temporary index when the atomic index rename fails', async () => {
    const pdf = await twoPagePdfWithJpeg(true);
    const before = fs.readdirSync(ASSETS_DIR).sort();
    const indexFile = path.join(ASSETS_DIR, 'index.json');
    const index = fs.readFileSync(indexFile);
    const rename = fs.renameSync;
    const spy = vi.spyOn(fs, 'renameSync').mockImplementation((from, to) => {
      if (String(to) === indexFile) throw new Error('LABELLED atomic index rename failure');
      return rename(from, to);
    });
    let r: Awaited<ReturnType<typeof importPdf>>;
    try { r = await importPdf(pdf); } finally { spy.mockRestore(); }
    expect(r!.status).toBe(500);
    expect(fs.readFileSync(indexFile)).toEqual(index);
    expect(fs.readdirSync(ASSETS_DIR).sort()).toEqual(before);
  });

  it('refuses when source or licence is missing, applying nothing', async () => {
    const pdf = await twoPagePdfWithJpeg();
    const noLicense = await importPdf(pdf, { source: SOURCE });
    expect(noLicense.status).toBe(422);
    expect(noLicense.json.code).toBe('FACTORY_VALIDATION');
    const before = loadAssetIndex().length;
    const noSource = await importPdf(pdf, { license: LICENSE });
    expect(noSource.status).toBe(422);
    expect(loadAssetIndex()).toHaveLength(before);
  });

  it('refuses non-PDF bytes and encrypted PDFs with precise codes', async () => {
    const notPdf = await importPdf(Buffer.from('this is plain text, definitely not a pdf'));
    expect(notPdf.status).toBe(422);
    expect(notPdf.json.code).toBe('FACTORY_PDF_NOT_PDF');

    const enc = new PdfBuilder();
    enc.set(1, '<< /Type /Catalog /Pages 2 0 R >>');
    enc.set(2, '<< /Type /Pages /Kids [] /Count 0 >>');
    enc.set(20, '<< /Filter /Standard /V 2 /R 3 >>');
    const encrypted = await importPdf(enc.build(1, ' /Encrypt 20 0 R'));
    expect(encrypted.status).toBe(422);
    expect(encrypted.json.code).toBe('FACTORY_PDF_ENCRYPTED');
  });

  it('refuses to overwrite an unreadable asset index and changes nothing', async () => {
    const indexFile = path.join(ASSETS_DIR, 'index.json');
    fs.mkdirSync(ASSETS_DIR, { recursive: true });
    const before = new Set(fs.readdirSync(ASSETS_DIR));
    fs.writeFileSync(indexFile, '{ this is not valid json', 'utf8');
    try {
      const r = await importPdf(await twoPagePdfWithJpeg());
      expect(r.status).toBe(422);
      expect(r.json.code).toBe('FACTORY_ASSET_INDEX_UNREADABLE');
      // The corrupt bytes are preserved, and this import left no new picture file behind.
      expect(fs.readFileSync(indexFile, 'utf8')).toBe('{ this is not valid json');
      expect(fs.readdirSync(ASSETS_DIR).filter((f) => !before.has(f))).toEqual([]);
    } finally {
      fs.rmSync(indexFile, { force: true });
    }
  });

  it('the imported storyboard reaches the canonical draft route and creates no draft on its own', async () => {
    const imported = await importPdf(await twoPagePdfWithJpeg());
    expect(imported.status).toBe(201);
    // The import route never wrote a draft.
    expect(fs.existsSync(path.join(process.env.BUILDTRAKE_DATA!, 'factory', 'drafts'))).toBe(false);

    const created = await app.inject({
      method: 'POST',
      url: '/api/factory/drafts',
      payload: JSON.stringify({
        contentProfile: 'educational',
        format: 'landscape',
        channelBrandId: null,
        requestedSpeakers: [],
        referenceProjectId: null,
        visualLanguage: null,
        inputs: {
          brief: '',
          script: null,
          audioAssetId: null,
          visualAssetIds: imported.json.visualAssetIds,
          storyboard: imported.json.storyboard,
          narrationMode: 'none',
          captions: true,
          visualRoles: {},
          visualNotes: {},
        },
      }),
      headers: { 'content-type': 'application/json' },
    });
    expect(created.statusCode).toBe(201);
    const body = JSON.parse(created.body);
    const scenes = body.treatments.find((t: any) => t.id === body.selectedTreatmentId).scenes;
    expect(scenes.map((s: any) => s.id)).toEqual(['page-01', 'page-02']);
    expect(scenes[0].assetId).toBe(imported.json.visualAssetIds[0]);
  });
});
