/**
 * PDF storyboard import through the REAL multipart route (app.inject).
 *
 * Evidence labels:
 *  - Real parse evidence: the PDF bytes (including an embedded DCT JPEG) are built by the test and
 *    decoded by the built-in dependency-free parser. No PDF library and no provider are involved.
 *  - HTTP fixture evidence. Not browser evidence and not owner-media evidence.
 *  - The importer creates library assets and a storyboard but never a draft: the canonical draft
 *    route remains the single creation path, which the final test exercises end to end.
 */
