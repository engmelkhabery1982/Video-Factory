/**
 * Explicit video-audio policy (original / replace / add / silent) through the REAL routes.
 *
 * Evidence labels:
 *  - Real local engine evidence: the MP4 fixtures are produced and probed with the BUNDLED
 *    ffmpeg/ffprobe binaries (platform paths, never a PATH assumption). The audio-stream facts
 *    are therefore measured, not mocked.
 *  - HTTP fixture evidence (app.inject): drafts, intake patches, refusals and applies.
 *  - Not browser evidence and not owner-media evidence. No provider call is possible: the
 *    fetch double fails the test if one is attempted.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';

vi.hoisted(() => {
  const nodeFs = process.getBuiltinModule('node:fs') as typeof import('node:fs');
  const nodePath = process.getBuiltinModule('node:path') as typeof import('node:path');
  const os = process.getBuiltinModule('node:os') as typeof import('node:os');
  const root = nodeFs.mkdtempSync(nodePath.join(os.tmpdir(), 'factory-video-audio-'));
  process.env.BUILDTRAKE_DATA = nodePath.join(root, 'data');
  process.env.BUILDTRAKE_OUTPUT = nodePath.join(root, 'output');
  process.env.VF_PREVIEW_DISABLE = '1';
  return { root };
});

import { buildServerApp } from '../apps/api/src/server.js';
import { readEditorState } from '../apps/api/src/services/editor-store.js';
import { ffmpegPath, ffprobePath, ASSETS_DIR } from '../apps/api/src/services/platform.js';
import { loadAssetIndex, saveAssetIndex } from '../apps/api/src/routes/assets.js';
import { makeWav } from './gemini/helpers.js';

type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;

/** LABELLED TEST DOUBLE. A provider call fails the test — the policy path is fully local. */
const providerCalls = vi.hoisted(() => ({ n: 0 }));
const fetchDouble = vi.fn(async (url: string) => {
  providerCalls.n += 1;
  throw new Error(`TEST DOUBLE: a provider call was not expected: ${url}`);
});

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({
    method,
    url,
    payload: body === undefined ? undefined : JSON.stringify(body),
    headers: body === undefined ? {} : { 'content-type': 'application/json' },
  });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json };
}

function multipart(fileName: string, content: Buffer, mime: string, fields: Record<string, string>) {
  const boundary = '----arenaVidAudio';
  const parts: Buffer[] = [];
  for (const [name, value] of Object.entries(fields)) {
    parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="${name}"\r\n\r\n${value}\r\n`));
  }
  parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="${fileName}"\r\nContent-Type: ${mime}\r\n\r\n`));
  parts.push(content);
  parts.push(Buffer.from(`\r\n--${boundary}--\r\n`));
  return { headers: { 'content-type': `multipart/form-data; boundary=${boundary}` }, payload: Buffer.concat(parts) };
}

const SOURCE = 'Synthetic video fixture (generated by the test with bundled ffmpeg)';
const LICENSE = 'Synthetic fixture, test only';

async function uploadVideo(fileName: string, withAudio: boolean): Promise<{ id: string; hasAudio?: boolean }> {
  const dest = path.join(process.env.BUILDTRAKE_DATA!, fileName);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const args = ['-y', '-f', 'lavfi', '-i', 'testsrc=duration=5:size=160x90:rate=12'];
  if (withAudio) args.push('-f', 'lavfi', '-i', 'sine=frequency=440:duration=5', '-c:a', 'aac');
  else args.push('-an');
  args.push('-c:v', 'libx264', '-pix_fmt', 'yuv420p', dest);
  execFileSync(ffmpegPath(), args, { stdio: 'ignore' });
  // Independent ground truth from ffprobe, so the test does not trust the product's own measurement.
  const probe = execFileSync(ffprobePath(), ['-v', 'error', '-select_streams', 'a', '-show_entries', 'stream=codec_type', '-of', 'csv=p=0', dest], { encoding: 'utf8' });
  expect(probe.trim().length > 0).toBe(withAudio);
  const bytes = fs.readFileSync(dest);
  const res = await app.inject({
    method: 'POST',
    url: '/api/assets',
    ...multipart(fileName, bytes, 'video/mp4', { name: fileName.replace(/\.[^.]+$/, ''), kind: 'broll', source: SOURCE, license: LICENSE }),
  });
  if (res.statusCode !== 200) throw new Error(`video upload failed: ${res.statusCode} ${res.body}`);
  return res.json().asset;
}

async function uploadAudio(fileName: string): Promise<{ id: string }> {
  const wav = makeWav({ seconds: 2 });
  const res = await app.inject({
    method: 'POST',
    url: '/api/assets',
    ...multipart(fileName, wav, 'audio/wav', { name: fileName.replace(/\.[^.]+$/, ''), kind: 'sfx', source: SOURCE, license: LICENSE }),
  });
  if (res.statusCode !== 200) throw new Error(`audio upload failed: ${res.statusCode} ${res.body}`);
  return res.json().asset;
}

const panel = (id: string, assetId: string | null, narration = '') => ({
  id, narration, speakerId: null, assetId, startSec: null, endSec: null, locked: false,
});
const draftBody = (scenes: Array<Record<string, unknown>>, extra: Record<string, unknown> = {}) => ({
  contentProfile: 'educational',
  format: 'landscape',
  channelBrandId: null,
  requestedSpeakers: [],
  referenceProjectId: null,
  visualLanguage: null,
  inputs: {
    brief: '',
    script: null,
    audioAssetId: null,
    visualAssetIds: scenes.map((s) => s.assetId).filter(Boolean),
    storyboard: { version: 1, scenes },
    narrationMode: 'none',
    captions: true,
    visualRoles: {},
    visualNotes: {},
    ...extra,
  },
});

let silentVid: { id: string; hasAudio?: boolean };
let voicedVid: { id: string; hasAudio?: boolean };
let audio: { id: string };

beforeAll(async () => {
  vi.stubGlobal('fetch', fetchDouble);
  app = await buildServerApp();
  await app.ready();
  silentVid = await uploadVideo('silent.mp4', false);
  voicedVid = await uploadVideo('voiced.mp4', true);
  audio = await uploadAudio('tone.wav');
});

afterAll(async () => {
  vi.unstubAllGlobals();
  await app?.close();
});

describe('video upload measures the audio stream', () => {
  it('persists hasAudio=false for the silent clip and hasAudio=true for the voiced clip', () => {
    expect(silentVid.hasAudio).toBe(false);
    expect(voicedVid.hasAudio).toBe(true);
  });
});

describe('video audio policy through the real factory routes', () => {
  it('original on a silent video is a precise refusal naming the missing audio stream', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody([panel('p1', silentVid.id)], { videoAudioPolicy: 'original' }));
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('blocked');
    const reason = r.json.missing.map((m: any) => m.reason).join(' ');
    expect(reason).toMatch(/audio stream|no audio/i);
    expect(r.json.intake.videoAudioPolicy).toBe('original');
    // The draft has units, so the topic-only planner gate is not attached.
    expect(r.json.plannerGate).toBeNull();
  });

  it('silent policy on the same silent video applies, and the document records the policy with no kept audio', async () => {
    const created = await call('POST', '/api/factory/drafts', draftBody([panel('p1', silentVid.id)], { videoAudioPolicy: 'silent' }));
    expect(created.status).toBe(201);
    expect(created.json.status).not.toBe('blocked');
    const applied = await call('POST', `/api/factory/drafts/${created.json.draftId}/apply`, {
      expectedRevision: created.json.revision,
      confirmSpeechCalls: 0,
    });
    expect(applied.status).toBe(201);
    const doc = readEditorState(applied.json.projectId, 'long')?.document as any;
    expect(doc.videoAudioPolicy).toBe('silent');
    expect(doc.visualClips.every((c: any) => c.keepAudio !== true)).toBe(true);
    expect(providerCalls.n).toBe(0);
  });

  it('original on a video with a measured audio stream applies with keepAudio on exactly that clip', async () => {
    const created = await call('POST', '/api/factory/drafts', draftBody([panel('p1', voicedVid.id), panel('p2', silentVid.id)], { videoAudioPolicy: 'original' }));
    expect(created.status).toBe(201);
    // Scene p2 is the silent clip: the policy cannot keep audio it does not have.
    expect(created.json.status).toBe('blocked');
    expect(created.json.missing.map((m: any) => m.reason).join(' ')).toMatch(/audio stream|no audio/i);

    // Swap the second panel to the voiced clip via an intake PATCH; the policy now holds.
    const patched = await call('PATCH', `/api/factory/drafts/${created.json.draftId}/intake`, {
      expectedRevision: created.json.revision,
      storyboard: { version: 1, scenes: [panel('p1', voicedVid.id), panel('p2', voicedVid.id)] },
    });
    expect(patched.status).toBe(200);
    expect(patched.json.status).not.toBe('blocked');

    const applied = await call('POST', `/api/factory/drafts/${created.json.draftId}/apply`, {
      expectedRevision: patched.json.revision,
      confirmSpeechCalls: 0,
    });
    expect(applied.status).toBe(201);
    const doc = readEditorState(applied.json.projectId, 'long')?.document as any;
    expect(doc.videoAudioPolicy).toBe('original');
    const kept = doc.visualClips.filter((c: any) => c.keepAudio === true);
    expect(kept.length).toBe(2);
    expect(new Set(kept.map((c: any) => c.sourceAssetId))).toEqual(new Set([voicedVid.id]));
    expect(providerCalls.n).toBe(0);
  });

  it('replace without narration words or separate audio is refused; attaching audio clears it', async () => {
    const blocked = await call('POST', '/api/factory/drafts', draftBody([panel('p1', voicedVid.id)], { videoAudioPolicy: 'replace' }));
    expect(blocked.status).toBe(201);
    expect(blocked.json.status).toBe('blocked');
    expect(blocked.json.missing.map((m: any) => m.reason).join(' ')).toMatch(/replace|audio|narration/i);

    const reviewed = draftBody([panel('p1', voicedVid.id, 'Reviewed narration line.')], { videoAudioPolicy: 'replace', narrationMode: 'supplied' });
    const withAudio = await call('POST', '/api/factory/drafts', {
      ...reviewed,
      inputs: { ...reviewed.inputs, audioAssetId: audio.id },
    });
    expect(withAudio.status).toBe(201);
    expect(withAudio.json.status).not.toBe('blocked');
  });

  it('add policy keeps the measured clip audio alongside the supplied narration track', async () => {
    const base = draftBody([panel('p1', voicedVid.id, 'Reviewed narration line.')], { videoAudioPolicy: 'add', narrationMode: 'supplied' });
    const r = await call('POST', '/api/factory/drafts', { ...base, inputs: { ...base.inputs, audioAssetId: audio.id } });
    expect(r.status).toBe(201);
    // Clip audio plus a supplied narration track: nothing to generate, nothing blocked.
    expect(r.json.status).not.toBe('blocked');
    const applied = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, {
      expectedRevision: r.json.revision,
      confirmSpeechCalls: 0,
    });
    expect(applied.status).toBe(201);
    const doc = readEditorState(applied.json.projectId, 'long')?.document as any;
    expect(doc.videoAudioPolicy).toBe('add');
    expect(doc.visualClips.some((c: any) => c.keepAudio === true)).toBe(true);
  });

  it('add policy is refused when there is neither narration audio nor words to speak', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody([panel('p1', voicedVid.id)], { videoAudioPolicy: 'add' }));
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('blocked');
    expect(r.json.missing.map((m: any) => m.reason).join(' ')).toMatch(/add/i);
  });

  it('an unmeasurable clip is never claimed silent: original/add refuse precisely, silent still applies', async () => {
    // A library row whose file is absent and which carries no measured hasAudio: the probe cannot run.
    const danglingId = 'vid-dangling';
    saveAssetIndex([
      ...loadAssetIndex(),
      {
        id: danglingId, name: 'Dangling fixture clip', kind: 'broll', fileName: 'missing.mp4', path: 'missing.mp4',
        mimeType: 'video/mp4', sizeBytes: 1, tags: [], status: 'active', preferred: false,
        source: SOURCE, license: LICENSE, addedAt: new Date().toISOString(), usedIn: [], blocked: false,
      } as never,
    ]);
    expect(fs.existsSync(path.join(ASSETS_DIR, 'missing.mp4'))).toBe(false);

    const original = await call('POST', '/api/factory/drafts', draftBody([panel('p1', danglingId)], { videoAudioPolicy: 'original' }));
    expect(original.status).toBe(201);
    expect(original.json.status).toBe('blocked');
    const reason = original.json.missing.map((m: any) => m.reason).join(' ');
    expect(reason).toMatch(/could not be measured/);
    expect(reason).not.toMatch(/no audio stream/);

    const add = await call('POST', '/api/factory/drafts', draftBody([panel('p1', danglingId, 'Reviewed words.')], { videoAudioPolicy: 'add', narrationMode: 'generate' }));
    expect(add.json.missing.map((m: any) => m.reason).join(' ')).toMatch(/could not be measured/);

    // Silent never reads the clip's sound, so the unmeasurable probe must not add an audio-policy problem.
    // The only remaining block is the independent, generic file-missing check (the bytes really are absent).
    const silent = await call('POST', '/api/factory/drafts', draftBody([panel('p1', danglingId)], { videoAudioPolicy: 'silent' }));
    expect(silent.status).toBe(201);
    const silentReasons = silent.json.missing.map((m: any) => m.reason).join(' ');
    expect(silentReasons).toMatch(/missing from the library files/);
    expect(silentReasons).not.toMatch(/could not be measured|no audio stream/);
  });

  it('rejects an unknown policy value with a 422 validation error, applying nothing', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody([panel('p1', silentVid.id)], { videoAudioPolicy: 'keep-it-loud' }));
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_VALIDATION');
  });

  it('legacy drafts with no policy stay muted: no policy field, no keepAudio, no new missing items', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody([panel('p1', voicedVid.id)]));
    expect(r.status).toBe(201);
    expect(r.json.intake.videoAudioPolicy).toBeNull();
    const applied = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, {
      expectedRevision: r.json.revision,
      confirmSpeechCalls: 0,
    });
    expect(applied.status).toBe(201);
    const doc = readEditorState(applied.json.projectId, 'long')?.document as any;
    expect(doc.videoAudioPolicy).toBeUndefined();
    expect(doc.visualClips.every((c: any) => c.keepAudio !== true)).toBe(true);
  });
});

describe('no-material starting point over HTTP', () => {
  it('returns deterministic local_rules topic suggestions and rejects an unknown profile', async () => {
    const ok = await call('GET', '/api/factory/topic-suggestions?profile=educational&purpose=crane%20safety');
    expect(ok.status).toBe(200);
    expect(ok.json.route).toBe('local_rules');
    expect(ok.json.suggestions).toHaveLength(3);
    expect(ok.json.suggestions.some((s: any) => s.title.toLowerCase().includes('crane'))).toBe(true);

    const bad = await call('GET', '/api/factory/topic-suggestions?profile=marketing');
    expect(bad.status).toBe(422);
    expect(bad.json.code).toBe('FACTORY_VALIDATION');
  });

  it('a brief-only draft carries the exact planner gate and an actionable warning, never a bare unavailable', async () => {
    const r = await call('POST', '/api/factory/drafts', {
      contentProfile: 'educational',
      format: 'landscape',
      channelBrandId: null,
      requestedSpeakers: [],
      referenceProjectId: null,
      visualLanguage: null,
      inputs: { brief: 'A short explainer about pump maintenance', script: null, audioAssetId: null, visualAssetIds: [], storyboard: null },
    });
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('blocked');
    expect(r.json.plannerGate).toBeTruthy();
    expect(r.json.plannerGate.route).toBe('local_llm');
    expect(typeof r.json.plannerGate.reason).toBe('string');
    expect(r.json.plannerGate.reason.length).toBeGreaterThan(10);
    // The gate names the exact missing setting (an env var), not a bare "unavailable".
    expect(r.json.plannerGate.missing.join(' ')).toMatch(/LOCAL_LLM|endpoint|model/i);
    const warning = r.json.warnings.join(' ');
    expect(warning).toMatch(/Supply reviewed script text|storyboard|pictures/i);
    expect(providerCalls.n).toBe(0);
  });
});
