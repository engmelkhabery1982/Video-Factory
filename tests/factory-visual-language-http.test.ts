describe('six entry paths (HTTP, fixture)', () => {
  it('brief only: no scenes are invented, and the missing script is listed', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody({}, { script: null, brief: 'Only a brief' }));
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('blocked');
    expect(r.json.treatments).toEqual([]);
    expect(r.json.missing.map((m: any) => m.kind)).toEqual(['script']);
    expect(r.json.warnings.join(' ')).toMatch(/No text is generated here/);
  });

  it('script: three treatments carry the supplied sentences in order, unchanged, with the stored hash', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody());
    expect(r.status).toBe(201);
    expect(r.json.treatments).toHaveLength(3);
    // Unlocked treatments may reorder shots, but every supplied sentence appears exactly once, unchanged.
    for (const t of r.json.treatments) {
      expect(t.scenes.map((s: any) => s.narration).sort()).toEqual(EDU_SCRIPT.split('\n').sort());
      expect(t.scenes.every((s: any) => s.sourceUnitId === s.id)).toBe(true);
    }
    const stored = JSON.parse(fs.readFileSync(path.join(DRAFTS_DIR, `${r.json.draftId}.json`), 'utf8'));
    expect(stored.source.scriptSha256).toBe(sha(EDU_SCRIPT));
    expect(stored.visualLanguage).toBe('motion_explainer');
    // A numeric example without owner values is refused at Apply, listed as an exact missing item.
    expect(r.json.status).toBe('blocked');
    expect(r.json.missing.every((m: any) => m.kind === 'asset' && /needs supplied values/.test(m.reason))).toBe(true);
  });

  it('storyboard with approved timings: times are kept exactly and a supplied picture stays bound on a graphic-shaped shot', async () => {
    const r = await call('POST', '/api/factory/drafts', { ...draftBody({ format: 'portrait' }, { script: null, storyboard: { version: 1, scenes: [
      { id: 's1', narration: 'Check the window.', speakerId: null, assetId: 'fx-image-a', startSec: 0, endSec: 3 },
      { id: 's2', narration: 'Confirm the crew.', speakerId: null, assetId: null, startSec: 3, endSec: 6 },
    ] } }) });
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('review_required');
    const t = r.json.treatments[0];
    expect(t.scenes.map((s: any) => [s.startSec, s.endSec, s.timingSource])).toEqual([[0, 3, 'supplied'], [3, 6, 'supplied']]);
    const kept = t.scenes.find((s: any) => s.id === 's1');
    expect(kept.assetId).toBe('fx-image-a');
    expect(kept.assetOrigin).toBe('supplied');
    expect(kept.technique).not.toBe('kinetic_text');
    expect(kept.graphic).toBeNull();
  });

  it('storyboard with start after end is refused with 422 before any draft is written', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody({}, { script: null, storyboard: { version: 1, scenes: [{ id: 's1', narration: 'Check.', speakerId: null, assetId: null, startSec: 5, endSec: 2 }] } }));
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_VALIDATION');
  });

  it('video with narration: the approved audio is reused as supplied (duration only), the timing source is labelled estimated, and a clip is never a still', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody({ visualLanguage: 'documentary_footage' }, { audioAssetId: 'fx-audio-6s', visualAssetIds: ['fx-clip'] }));
    expect(r.status).toBe(201);
    expect(r.json.inputs.audioAssetId).toBe('fx-audio-6s');
    expect(r.json.inputs.audioDurationSec).toBe(6);
    expect(r.json.timingPlan.timingSource).toBe('estimated_text_length');
    expect(r.json.timingPlan.label).toMatch(/not audio-aligned/);
    for (const t of r.json.treatments) {
      for (const s of t.scenes) {
        if (s.assetId === 'fx-clip') expect(s.technique).not.toBe('still_image');
      }
    }
  });

  it('a visual language that is not registered is refused before planning', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody({ visualLanguage: 'hologram' }));
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_VALIDATION');
  });

  it('a legacy draft (no language) reads back with null language and no technique on any shot', async () => {
    const r = await call('POST', '/api/factory/drafts', draftBody({ visualLanguage: null }));
    expect(r.status).toBe(201);
    expect(r.json.visualLanguage).toBeNull();
    const again = await call('GET', `/api/factory/drafts/${r.json.draftId}`);
    expect(again.status).toBe(200);
    expect(again.json.visualLanguage).toBeNull();
    for (const t of again.json.treatments) for (const s of t.scenes) expect(s.technique ?? null).toBeNull();
  });
});

describe('visual-language changes on the real PATCH route', () => {
  async function scriptDraft() {
    const r = await call('POST', '/api/factory/drafts', draftBody());
    expect(r.status).toBe(201);
    const treatment = r.json.treatments[0];
    return { id: r.json.draftId as string, treatment, rev: r.json.revision as number };
  }

  it('a row with owner values is kept; a language change without confirmation is refused with the shot ids, nothing saved', async () => {
    const d = await scriptDraft();
    const graphic = buildNumericGraphic(
      { title: '', scaleMax: '10', rows: [{ label: 'Truck', value: '7', unit: 'h' }, { label: 'Crew', value: '9.5', unit: 'h' }] },
      'landscape',
      3,
    );
    const scenes = d.treatment.scenes.map((s: any) => (s.id === 'u02' ? { ...s, technique: 'numeric_comparison', graphic } : s));
    const set = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 0, selectedTreatmentId: d.treatment.id, scenes, speakers: [] });
    expect(set.status).toBe(200);
    expect(set.json.status).toBe('review_required');
    expect(set.json.revision).toBe(1);

    const refused = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 1, selectedTreatmentId: d.treatment.id, visualLanguage: 'screen_tutorial', scenes: set.json.treatments[0].scenes, speakers: [] });
    expect(refused.status).toBe(422);
    expect(refused.json.code).toBe('FACTORY_VALIDATION');
    // The route flattens FactoryError details into the body (existing convention): the shot ids are top-level.
    expect(refused.json.sceneIds).toContain('u02');

    const after = await call('GET', `/api/factory/drafts/${d.id}`);
    expect(after.json.visualLanguage).toBe('motion_explainer');
    expect(after.json.revision).toBe(1);
    const selected = after.json.treatments.find((t: any) => t.id === d.treatment.id);
    expect(selected.scenes.find((s: any) => s.id === 'u02').graphic).toEqual(graphic);
  });

  it('a stale revision on a language change is refused with 409 and the current revision', async () => {
    const d = await scriptDraft();
    const stale = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 7, selectedTreatmentId: d.treatment.id, visualLanguage: 'kinetic_typography', scenes: d.treatment.scenes, speakers: [] });
    expect(stale.status).toBe(409);
    expect(stale.json.code).toBe('FACTORY_REVISION_CONFLICT');
    expect(stale.json.currentRevision).toBe(0);
  });

  it('a confirmed reset changes the language and every shot gets only a technique that language allows', async () => {
    const d = await scriptDraft();
    const r = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 0, selectedTreatmentId: d.treatment.id, visualLanguage: 'kinetic_typography', resetShotTechniques: true, scenes: d.treatment.scenes, speakers: [] });
    expect(r.status).toBe(200);
    expect(r.json.visualLanguage).toBe('kinetic_typography');
    for (const s of r.json.treatments[0].scenes) {
      if (s.technique) expect(languageAllowsTechnique('kinetic_typography', s.technique)).toBe(true);
    }
    expect(r.json.treatments[0].scenes.map((s: any) => s.narration)).toEqual(EDU_SCRIPT.split('\n'));
  });

  it('a locked shot refuses a language change with 423 and the draft is unchanged', async () => {
    const d = await scriptDraft();
    const scenes = d.treatment.scenes.map((s: any) => (s.id === 'u01' ? { ...s, locked: true } : s));
    const locked = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 0, selectedTreatmentId: d.treatment.id, scenes, speakers: [] });
    expect(locked.status).toBe(200);
    const refused = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 1, selectedTreatmentId: d.treatment.id, visualLanguage: 'mixed', resetShotTechniques: true, scenes: locked.json.treatments[0].scenes, speakers: [] });
    expect(refused.status).toBe(423);
    expect(refused.json.code).toBe('FACTORY_SCENE_LOCKED');
    const after = await call('GET', `/api/factory/drafts/${d.id}`);
    expect(after.json.visualLanguage).toBe('motion_explainer');
  });

  it('an unregistered language in a PATCH is refused with 422', async () => {
    const d = await scriptDraft();
    const r = await call('PATCH', `/api/factory/drafts/${d.id}`, { expectedRevision: 0, selectedTreatmentId: d.treatment.id, visualLanguage: 'hologram', scenes: d.treatment.scenes, speakers: [] });
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_VALIDATION');
  });

  it('a draft with a numeric shot that has no values is refused at Apply with the exact missing item and no project written', async () => {
    const d = await scriptDraft();
    const r = await call('POST', `/api/factory/drafts/${d.id}/apply`, { expectedRevision: 0 });
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_INPUTS_REQUIRED');
    expect(JSON.stringify(r.json)).toMatch(/u02|numeric|values/i);
  });
});
