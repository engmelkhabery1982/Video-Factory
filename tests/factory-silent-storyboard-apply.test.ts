import { buildServerApp } from '../apps/api/src/server.js';
import { readEditorState } from '../apps/api/src/services/editor-store.js';
import sharp from 'sharp';

type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;

/** LABELLED TEST DOUBLE. A provider call fails the test. */
const providerCalls = vi.hoisted(() => ({ n: 0 }));
const fetchDouble = vi.fn(async (url: string) => {
  providerCalls.n += 1;
  throw new Error(`TEST DOUBLE: a provider call was not expected: ${url}`);
});

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({ method, url, payload: body === undefined ? undefined : JSON.stringify(body), headers: body === undefined ? {} : { 'content-type': 'application/json' } });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json };
}

function multipart(fileName: string, content: Buffer, mime: string, fields: Record<string, string>) {
  const boundary = '----arenaSilentSb';
  const parts: Buffer[] = [];
  for (const [name, value] of Object.entries(fields)) parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="${name}"\r\n\r\n${value}\r\n`));
  parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="${fileName}"\r\nContent-Type: ${mime}\r\n\r\n`));
  parts.push(content);
  parts.push(Buffer.from(`\r\n--${boundary}--\r\n`));
  return { headers: { 'content-type': `multipart/form-data; boundary=${boundary}` }, payload: Buffer.concat(parts) };
}

async function upload(name: string, colour: string): Promise<{ id: string }> {
  const png = await sharp({ create: { width: 16, height: 9, channels: 3, background: colour } }).png().toBuffer();
  const res = await app.inject({ method: 'POST', url: '/api/assets', ...multipart(name, png, 'image/png', { name: name.replace(/\.[^.]+$/, ''), kind: 'screenshot', source: 'Silent storyboard fixture (synthetic, generated by the test)', license: 'Synthetic fixture, test only' }) });
  if (res.statusCode !== 200) throw new Error(`fixture upload failed for ${name}: ${res.statusCode} ${res.body}`);
  return res.json().asset;
}

const panel = (id: string, assetId: string | null) => ({ id, narration: '', speakerId: null, assetId, startSec: null, endSec: null, locked: false });

let A: { id: string }, B: { id: string };

beforeAll(async () => {
  vi.stubGlobal('fetch', fetchDouble);
  app = await buildServerApp();
  await app.ready();
  A = await upload('silent-a.png', '#2a6');
  B = await upload('silent-b.png', '#a62');
});

afterAll(async () => {
  vi.unstubAllGlobals();
  await app?.close();
});

describe('silent storyboard with blank panels: duplicate, reorder and remove reach the applied editor', () => {
  it('the edited order of pictures is what Apply writes to visualClips, and no speech or provider is used', async () => {
    const created = await call('POST', '/api/factory/drafts', {
      contentProfile: 'educational', format: 'landscape', channelBrandId: null, requestedSpeakers: [], referenceProjectId: null, visualLanguage: null,
      inputs: {
        brief: '', script: null, audioAssetId: null, visualAssetIds: [A.id, B.id],
        storyboard: { version: 1, scenes: [panel('p1', A.id), panel('p2', B.id)] },
        narrationMode: 'none', captions: false,
      },
    });
    expect(created.status).toBe(201);
    expect(created.json.status).toBe('review_required');
    const draftId = created.json.draftId as string;
    let revision = created.json.revision as number;

    // 1. Duplicate the blank panel p1 as p1-copy (same picture).
    const dup = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, {
      expectedRevision: revision,
      storyboard: { version: 1, scenes: [panel('p1', A.id), panel('p1-copy', A.id), panel('p2', B.id)] },
    });
    expect(dup.status).toBe(200);
    revision = dup.json.revision;

    // 2. Reorder: p2 first, then p1, then the copy.
    const reordered = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, {
      expectedRevision: revision,
      storyboard: { version: 1, scenes: [panel('p2', B.id), panel('p1', A.id), panel('p1-copy', A.id)] },
    });
    expect(reordered.status).toBe(200);
    revision = reordered.json.revision;

    // 3. Remove the copy.
    const removed = await call('PATCH', `/api/factory/drafts/${draftId}/intake`, {
      expectedRevision: revision,
      storyboard: { version: 1, scenes: [panel('p2', B.id), panel('p1', A.id)] },
    });
    expect(removed.status).toBe(200);
    revision = removed.json.revision;

    // The intake holds the edited list.
    const intakeIds = (removed.json.intake?.storyboard?.scenes ?? []).map((s: { id: string }) => s.id);
    expect(intakeIds).toEqual(['p2', 'p1']);

    // 4. Apply. The applied editor document carries the same order of pictures.
    const a = await call('POST', `/api/factory/drafts/${draftId}/apply`, { expectedRevision: revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    expect(a.json.speechGenerated).toBe(0);
    expect(providerCalls.n).toBe(0);

    const doc = readEditorState(a.json.projectId, 'long')?.document as any;
    const clips = [...(doc.visualClips ?? [])].sort((x: any, y: any) => (x.startSec ?? x.start ?? 0) - (y.startSec ?? y.start ?? 0));
    expect(clips.map((c: any) => c.sourceAssetId)).toEqual([B.id, A.id]);
    expect(doc.audioClips.length).toBe(0);
  });

  it('the upload directory is not used by this test and nothing is written outside the isolated data directory', () => {
    expect(fs.existsSync(path.join(process.env.BUILDTRAKE_DATA!, 'factory', 'drafts'))).toBe(true);
  });
});
