describe('two speakers, exact spend, selective regeneration, derivative without spend', () => {
  it('a two-speaker plan becomes a draft: voice and delivery style are separate fields per speaker, and scenes carry their speaker', async () => {
    const created = await call('POST', '/api/factory/ai/plans', { profile: 'educational', format: 'landscape', brief: 'Explain why deliveries must be confirmed the night before.' });
    const job = await waitForJob(created.json.job.id);
    expect(job.status).toBe('succeeded');
    const draft = await call('POST', `/api/factory/ai/plans/${job.id}/draft`, {
      format: 'landscape',
      speakers: [
        { label: 'narrator', voice: 'Kore', style: 'calm and clear' },
        { label: 'presenter', voice: 'Puck', style: 'brisk and warm' },
      ],
    });
    expect(draft.status).toBe(201);
    ids.draftId = draft.json.draftId;
    expect(draft.json.speakers).toEqual([
      expect.objectContaining({ id: 'narrator', voiceId: 'Kore', provider: 'gemini', style: 'calm and clear' }),
      expect.objectContaining({ id: 'presenter', voiceId: 'Puck', provider: 'gemini', style: 'brisk and warm' }),
    ]);
    const t1 = draft.json.treatments.find((t: any) => t.id === 'T1');
    const speakerOfLine = Object.fromEntries(t1.scenes.map((s: any) => [s.sourceUnitId, s.speakerId]));
    expect(speakerOfLine).toEqual({ L01: 'narrator', L02: 'presenter', L03: 'narrator' });
    // Voice identity is not a style string, and style is not part of the narration text.
    for (const sp of draft.json.speakers) expect(sp.voiceId).not.toMatch(/ /);
    expect(t1.scenes.find((s: any) => s.sourceUnitId === 'L02').narration).toBe('Confirm the delivery window the night before with the supplier.');
  });

  it('binds media, then previews the exact count: three lines, three calls, nothing spent by the preview', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const scenes = d.json.treatments.find((t: any) => t.id === 'T1').scenes.map((s: any) => ({
      ...s,
      assetId: s.shot?.assetNeed === 'screen_recording_needed' ? 'fx-sp-video' : s.shot?.assetNeed === 'image_needed' ? 'fx-sp-b' : 'fx-sp-a',
    }));
    const patched = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, { expectedRevision: d.json.revision, selectedTreatmentId: 'T1', scenes, speakers: [] });
    expect(patched.status, patched.raw).toBe(200);
    const before = provider.tts.length;
    const preview = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(preview.json.speechCalls).toBe(3);
    expect(preview.json.canApply).toBe(true);
    expect(provider.tts.length).toBe(before);
  });

  it('a count that does not match is refused without a call; the confirmed count makes one unary call per line with the right voice and style', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const wrong = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 2 });
    expect(wrong.status).toBe(422);
    expect(wrong.json.speechCalls).toBe(3);
    expect(provider.tts.length).toBe(0);

    const applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 3 });
    expect(applied.status).toBe(201);
    expect(provider.tts.length).toBe(3);
    const byText = new Map(provider.tts.map((b: any) => [b.input[0].content[0].text, b]));
    const l02 = byText.get('Confirm the delivery window the night before with the supplier.');
    expect(l02.generation_config.speech_config[0].voice).toBe('Puck');
    expect(l02.input[0].content[0].annotations[0]).toEqual({ type: 'speech_metadata', style: 'brisk and warm' });
    const l01 = byText.get('A concrete pour was booked for seven, but the truck arrived at nine.');
    expect(l01.generation_config.speech_config[0].voice).toBe('Kore');
    expect(l01.input[0].content[0].annotations[0]).toEqual({ type: 'speech_metadata', style: 'calm and clear' });
    // The narration text carries no delivery direction.
    expect(l02.input[0].content[0].text).not.toMatch(/brisk|warm/);
    ids.sourceJson = path.join(DRAFTS_DIR, `${ids.draftId}.json`);
  });

  it('the saved speakers and speaker assignments survive a server restart', async () => {
    await app.close();
    app = await buildServerApp();
    await app.ready();
    const g = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    expect(g.status).toBe(200);
    expect(g.json.speakers).toEqual([
      expect.objectContaining({ id: 'narrator', voiceId: 'Kore', style: 'calm and clear' }),
      expect.objectContaining({ id: 'presenter', voiceId: 'Puck', style: 'brisk and warm' }),
    ]);
    const t1 = g.json.treatments.find((t: any) => t.id === 'T1');
    expect(Object.fromEntries(t1.scenes.map((s: any) => [s.sourceUnitId, s.speakerId]))).toEqual({ L01: 'narrator', L02: 'presenter', L03: 'narrator' });
    expect(provider.tts.length).toBe(3);
  });

  it('changing one speaker\'s style counts only that speaker\'s line; the other speaker\'s clips stay byte-for-byte', async () => {
    const narratorBefore = clipsByVoice('Kore');
    expect(narratorBefore.size).toBe(2);
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const edit = await call('PATCH', `/api/factory/drafts/${ids.draftId}/generated`, {
      expectedRevision: d.json.revision,
      speakers: [{ id: 'presenter', style: 'slower and calmer' }],
    });
    expect(edit.status, edit.raw).toBe(200);
    expect(edit.json.speakers.find((s: any) => s.id === 'presenter')).toMatchObject({ voiceId: 'Puck', style: 'slower and calmer' });
    expect(edit.json.speakers.find((s: any) => s.id === 'narrator')).toMatchObject({ voiceId: 'Kore', style: 'calm and clear' });

    const before = provider.tts.length;
    const preview = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(preview.json.speechCalls).toBe(1);
    expect(preview.json.sceneIds).toHaveLength(1);
    expect(provider.tts.length).toBe(before);

    // Refused without the explicit count, and nothing is spent.
    const noCount = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: edit.json.revision });
    expect(noCount.status).toBe(422);
    expect(provider.tts.length).toBe(before);

    const applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: edit.json.revision, confirmSpeechCalls: 1 });
    expect(applied.status).toBe(201);
    expect(provider.tts.length).toBe(before + 1);
    expect(provider.tts[before].input[0].content[0].annotations[0]).toEqual({ type: 'speech_metadata', style: 'slower and calmer' });
    expect(provider.tts[before].generation_config.speech_config[0].voice).toBe('Puck');
    expect(clipsByVoice('Kore')).toEqual(narratorBefore);
  });

  it('deriving a rewrite of one narrator line creates a derivative and does NOT spend; its preview counts exactly the one changed line', async () => {
    const sourceHash = hashFile(ids.sourceJson);
    const before = provider.tts.length;
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const out = await call('POST', `/api/factory/drafts/${ids.draftId}/derive`, {
      expectedRevision: d.json.revision,
      edits: [{ unitId: 'L03', narration: 'Write the confirmed time on the site board for every crew.' }],
    });
    expect(out.status).toBe(201);
    ids.derivedId = out.json.draftId;
    expect(provider.tts.length).toBe(before);
    expect(hashFile(ids.sourceJson)).toBe(sourceHash);

    const preview = await call('GET', `/api/factory/drafts/${ids.derivedId}/apply-preview`);
    expect(preview.json.speechCalls).toBe(1);
    expect(preview.json.canApply).toBe(false);
    expect(preview.json.blockers.some((b: { kind: string }) => b.kind === 'review')).toBe(true);
    expect(provider.tts.length).toBe(before);
  });

  it('applying the derivative before review is refused with no call; review spends nothing; the confirmed count applies one call', async () => {
    const before = provider.tts.length;
    const d = await call('GET', `/api/factory/drafts/${ids.derivedId}`);
    const early = await call('POST', `/api/factory/drafts/${ids.derivedId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 1 });
    expect(early.status).toBeGreaterThanOrEqual(400);
    expect(provider.tts.length).toBe(before);

    const reviewed = await call('POST', `/api/factory/drafts/${ids.derivedId}/review`, { expectedRevision: d.json.revision });
    expect(reviewed.status).toBe(200);
    expect(provider.tts.length).toBe(before);

    const preview = await call('GET', `/api/factory/drafts/${ids.derivedId}/apply-preview`);
    expect(preview.json.canApply).toBe(true);
    expect(preview.json.speechCalls).toBe(1);
    const narratorBefore = clipsByVoice('Kore');
    const presenterBefore = clipsByVoice('Puck');

    const applied = await call('POST', `/api/factory/drafts/${ids.derivedId}/apply`, { expectedRevision: reviewed.json.revision, confirmSpeechCalls: 1 });
    expect(applied.status).toBe(201);
    expect(provider.tts.length).toBe(before + 1);
    expect(provider.tts[before].input[0].content[0].text).toBe('Write the confirmed time on the site board for every crew.');
    // Unchanged clips of the derivative are the source's bytes, not re-synthesized.
    for (const [id, hash] of narratorBefore) expect(clipsByVoice('Kore').get(id)).toBe(hash);
    for (const [id, hash] of presenterBefore) expect(clipsByVoice('Puck').get(id)).toBe(hash);
  });

  it('the source draft is unchanged, the derivative does not change it, and the ledger never exceeded the configured turns', async () => {
    const g = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    expect(g.json.derivedFrom).toBeNull();
    const derivative = await call('GET', `/api/factory/drafts/${ids.derivedId}`);
    expect(derivative.json.derivedFrom).toMatchObject({ draftId: ids.draftId });
    expect(provider.tts.length).toBeLessThanOrEqual(6);
    expect(provider.tts.length).toBe(5);
  });
});
