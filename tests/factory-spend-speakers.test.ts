// Must equal the server default text model: live evidence is bound to the key and BOTH models (gemini-service evidenceBinding).
const TEXT_MODEL = 'gemini-3.8-flash';
const TTS_MODEL = 'gemini-3.8-flash-tts';

/** Two speakers: the plan's line L02 is spoken by a second speaker, "presenter". */
function twoSpeakerPlan(): Record<string, unknown> {
  const plan = fixtureEducationalPlan() as any;
  plan.script.lines[1].speaker = 'presenter';
  return plan;
}

/** LABELLED TEST DOUBLE for the Gemini REST endpoint. Records every turn request. */
const provider = vi.hoisted(() => ({ text: 0, tts: [] as any[] }));
const fetchSpy = vi.fn(async (url: string, init: { body: string }) => {
  const u = String(url);
  const body = JSON.parse(init.body);
  const json = (payload: unknown, status = 200) => ({ ok: status < 400, status, json: async () => payload });
  if (u.endsWith('/v1/chat/completions')) {
    provider.text += 1;
    return json({ choices: [{ message: { content: JSON.stringify(twoSpeakerPlan()) }, finish_reason: 'stop' }] });
  }
  if (u.endsWith('/interactions') && body.model === TTS_MODEL) {
    provider.tts.push(body);
    const wav = makeWav({ seconds: 0.5 + provider.tts.length * 0.05 });
    return json({ status: 'completed', steps: [{ type: 'model_output', content: [{ type: 'audio', mime_type: 'audio/wav', data: b64(wav) }] }] });
  }
  throw new Error(`TEST DOUBLE: unexpected provider URL ${u}`);
});

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({
    method,
    url,
    payload: body === undefined ? undefined : JSON.stringify(body),
    headers: body === undefined ? {} : { 'content-type': 'application/json' },
  });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json, raw: res.body };
}

function seedAsset(id: string, mimeType: string, fileName: string, bytes: Buffer, extra: Record<string, unknown> = {}): void {
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  fs.writeFileSync(path.join(ASSETS_DIR, fileName), bytes);
  saveAssetIndex([
    ...loadAssetIndex(),
    {
      id, name: `Fixture ${id}`, kind: 'broll', fileName, path: fileName, mimeType, sizeBytes: bytes.length,
      tags: [], status: 'active', preferred: false, source: 'Fixture (synthetic, generated by the test)', license: 'Test fixture',
      addedAt: new Date().toISOString(), usedIn: [], blocked: false, ...extra,
    } as never,
  ]);
}

async function waitForJob(jobId: string): Promise<any> {
  for (let i = 0; i < 400; i++) {
    const r = await call('GET', `/api/factory/ai/jobs/${jobId}`);
    if (r.json.job.status !== 'running') return r.json.job;
    await new Promise((res) => setTimeout(res, 10));
  }
  throw new Error('job did not finish');
}

/** Speech clips by voice, read from disk: byte-for-byte comparison, not just asset ids. */
function clipsByVoice(voice: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const a of loadAssetIndex() as any[]) {
    if (!a.id.startsWith('factory-speech-') || !String(a.source ?? '').includes(`voice ${voice},`)) continue;
    out.set(a.id, createHash('sha256').update(fs.readFileSync(path.join(ASSETS_DIR, a.fileName))).digest('hex'));
  }
  return out;
}

const hashFile = (file: string) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');

