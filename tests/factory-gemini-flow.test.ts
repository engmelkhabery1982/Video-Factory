/**
 * Milestone 3 end-to-end, through the REAL registered server (buildServerApp).
 *
 * Flow: plan job -> draft (3 treatments kept) -> edit unapproved narration -> bind assets ->
 * apply with an explicit call count -> idempotent reuse -> treatment switch reuses clips ->
 * selective regeneration -> provider 401 rolls back -> budget refusal before any call.
 *
 * LABELLED TEST DOUBLES: the Gemini provider is a scripted fetch double that returns the
 * fixture plan and synthesized silent WAV clips. Evidence written here is FIXTURE evidence
 * (a verification record created by the test), not a live provider result.
 */
