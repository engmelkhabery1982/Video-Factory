type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;

const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==', 'base64');
const TEXT_MODEL = 'gemini-2.5-flash';
const TTS_MODEL = 'gemini-3.8-flash-tts';

/** LABELLED TEST DOUBLE for the Gemini REST endpoint. Records every call. */
const provider = vi.hoisted(() => ({ text: [] as unknown[], tts: [] as unknown[], failNextTts: 0, ttsCounter: 0 }));
const fetchSpy = vi.fn(async (url: string, init: { body: string }) => {
  const u = String(url);
  const body = JSON.parse(init.body);
  const json = (payload: unknown, status = 200) => ({ ok: status < 400, status, json: async () => payload });
  if (u.includes(`/models/${TEXT_MODEL}:generateContent`)) {
    provider.text.push(body);
    return json({ candidates: [{ content: { parts: [{ text: JSON.stringify(fixtureEducationalPlan()) }] }, finishReason: 'STOP' }] });
  }
  if (u.includes(`/models/${TTS_MODEL}:generateContent`)) {
    provider.tts.push(body);
    if (provider.failNextTts > 0) {
      provider.failNextTts -= 1;
      return json({ error: { message: 'API key not valid' } }, 401);
    }
    provider.ttsCounter += 1;
    const wav = makeWav({ seconds: 0.5 + provider.ttsCounter * 0.05 });
    return json({ candidates: [{ content: { parts: [{ inlineData: { mimeType: 'audio/wav', data: b64(wav) } }] }, finishReason: 'STOP' }] });
  }
  throw new Error(`TEST DOUBLE: unexpected provider URL ${u}`);
});

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({
    method,
    url,
    payload: body === undefined ? undefined : JSON.stringify(body),
    headers: body === undefined ? {} : { 'content-type': 'application/json' },
  });
  let json: any = null;
  try {
    json = JSON.parse(res.body);
  } catch {
    json = res.body;
  }
  return { status: res.statusCode, json, raw: res.body };
}

function seedImage(id: string): void {
  const fileName = `${id}.png`;
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  fs.writeFileSync(path.join(ASSETS_DIR, fileName), PNG);
  saveAssetIndex([
    ...loadAssetIndex(),
    {
      id, name: `Fixture ${id}`, kind: 'broll', fileName, path: fileName, mimeType: 'image/png', sizeBytes: PNG.length,
      tags: [], status: 'active', preferred: false, source: 'Fixture (synthetic, generated by the test)', license: 'Test fixture',
      addedAt: new Date().toISOString(), usedIn: [], blocked: false,
    } as never,
  ]);
}

/** LABELLED FIXTURE VIDEO: a video-typed library entry with fixture bytes. Binding checks type, status, licence and hash, not decoding. */
function seedVideo(id: string): void {
  const fileName = `${id}.mp4`;
  const bytes = Buffer.from('FIXTURE-VIDEO-NOT-DECODED');
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  fs.writeFileSync(path.join(ASSETS_DIR, fileName), bytes);
  saveAssetIndex([
    ...loadAssetIndex(),
    {
      id, name: `Fixture ${id}`, kind: 'broll', fileName, path: fileName, mimeType: 'video/mp4', sizeBytes: bytes.length, durationSec: 30,
      tags: [], status: 'active', preferred: false, source: 'Fixture (synthetic, generated by the test)', license: 'Test fixture',
      addedAt: new Date().toISOString(), usedIn: [], blocked: false,
    } as never,
  ]);
}

async function waitForJob(jobId: string): Promise<any> {
  for (let i = 0; i < 400; i++) {
    const r = await call('GET', `/api/factory/ai/jobs/${jobId}`);
    if (r.json.job.status !== 'running') return r.json.job;
    await new Promise((res) => setTimeout(res, 10));
  }
  throw new Error('job did not finish');
}

function speechAssets(): any[] {
  return loadAssetIndex().filter((a: any) => a.id.startsWith('factory-speech-') && (a.tags ?? []).includes('gemini-tts'));
}

const ids = { draftId: '', jobId: '', planDraft: null as any };

