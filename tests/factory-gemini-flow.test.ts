describe('Gemini plan to apply, end to end (labelled provider double)', () => {
  it('status is network-free and reports the fixture evidence bound to this key and model', async () => {
    const before = fetchSpy.mock.calls.length;
    const r = await call('GET', '/api/factory/ai/status');
    expect(r.status).toBe(200);
    expect(fetchSpy.mock.calls.length).toBe(before);
    expect(r.json.verification.binding).toBe('current');
    expect(r.json.productionSpeech.en.ready).toBe(true);
    expect(r.json.productionSpeech.ar.ready).toBe(false);
    expect(r.raw).not.toContain('FIXTURE-KEY-FLOW');
  });

  it('plan job runs once, persists, and polling makes no further provider call', async () => {
    const created = await call('POST', '/api/factory/ai/plans', {
      profile: 'educational',
      format: 'landscape',
      brief: 'Explain why deliveries must be confirmed the night before.',
    });
    expect(created.status).toBe(202);
    ids.jobId = created.json.job.id;
    const job = await waitForJob(ids.jobId);
    expect(job.status).toBe('succeeded');
    expect(provider.text.length).toBe(1);
    await call('GET', `/api/factory/ai/jobs/${ids.jobId}`);
    expect(provider.text.length).toBe(1);
  });

  it('converts the plan into a draft that keeps all three semantic treatments, marked gemini_plan', async () => {
    const r = await call('POST', `/api/factory/ai/plans/${ids.jobId}/draft`, {
      format: 'landscape',
      speakers: [{ label: 'narrator', voice: 'Kore', style: 'calm and clear' }],
    });
    expect(r.status).toBe(201);
    ids.draftId = r.json.draftId;
    expect(r.json.generationMode).toBe('gemini_plan');
    expect(r.json.treatments.map((t: any) => t.id)).toEqual(['T1', 'T2', 'T3']);
    expect(new Set(r.json.treatments.map((t: any) => t.title)).size).toBe(3);
    expect(r.json.speakers).toEqual([expect.objectContaining({ id: 'narrator', voiceId: 'Kore', provider: 'gemini', style: 'calm and clear' })]);
    // Missing assets are listed. Speech is ready (fixture evidence + budget), so only visuals are missing:
    // stills for image needs and a real recording for the screen-recording need.
    expect(r.json.missing.length).toBeGreaterThan(0);
    expect(r.json.missing.every((m: any) => m.kind === 'image' || m.kind === 'recording')).toBe(true);
    expect(r.json.missing.some((m: any) => m.kind === 'recording')).toBe(true);
    expect(r.json.status).toBe('blocked');
    ids.planDraft = r.json;
    // No provider call happened on conversion.
    expect(provider.tts.length).toBe(0);
  });

  it('converting the same plan again is idempotent (200, same draft)', async () => {
    const r = await call('POST', `/api/factory/ai/plans/${ids.jobId}/draft`, { format: 'landscape' });
    expect(r.status).toBe(200);
    expect(r.json.draftId).toBe(ids.draftId);
  });

  it('shot list lists prompts for missing images and a markdown package from the same data', async () => {
    const r = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    expect(r.status).toBe(200);
    expect(r.json.scenes).toHaveLength(3);
    expect(r.json.scenes.every((s: any) => s.status === 'missing')).toBe(true);
    expect(r.json.scenes.find((s: any) => s.assetNeed === 'image_needed').prompt).toMatch(/16:9/);
    const md = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list?format=md`);
    expect(md.raw).toContain('# Shot list');
    expect(md.raw).toContain('Text only');
  });

  it('edits unapproved narration: one line changes in every treatment, and stale revisions are refused', async () => {
    const r = await call('PATCH', `/api/factory/drafts/${ids.draftId}/generated`, {
      expectedRevision: 0,
      edits: [{ unitId: 'L01', narration: 'The truck arrived at nine, not seven, as booked.' }],
    });
    expect(r.status).toBe(200);
    expect(r.json.revision).toBe(1);
    for (const t of r.json.treatments) {
      const scene = t.scenes.find((s: any) => s.sourceUnitId === 'L01');
      expect(scene.narration).toBe('The truck arrived at nine, not seven, as booked.');
    }
    const stale = await call('PATCH', `/api/factory/drafts/${ids.draftId}/generated`, {
      expectedRevision: 0,
      edits: [{ unitId: 'L01', narration: 'Stale edit.' }],
    });
    expect(stale.status).toBe(409);
    expect(stale.json.code).toBe('FACTORY_REVISION_CONFLICT');
  });

  it('a supplied (non-generated) draft cannot be edited through the generated route', async () => {
    const created = await call('POST', '/api/factory/drafts', {
      contentProfile: 'educational',
      format: 'landscape',
      channelBrandId: null,
      inputs: {
        brief: 'Concrete delivery windows',
        script: 'Many sites lose a day when a crane waits for a delivery nobody confirmed.\nConfirm the window the night before.',
        audioAssetId: null,
        visualAssetIds: [],
        storyboard: null,
      },
      requestedSpeakers: [],
      referenceProjectId: null,
    });
    expect(created.status).toBe(201);
    const r = await call('PATCH', `/api/factory/drafts/${created.json.draftId}/generated`, { expectedRevision: 0, edits: [] });
    expect(r.status).toBe(409);
    expect(r.json.code).toBe('FACTORY_NOT_GENERATED');
  });

  it('binds library assets to every scene of a treatment (existing PATCH path)', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const t1 = d.json.treatments.find((t: any) => t.id === 'T1');
    // A screen-recording need is bound to a video. A still would be refused (see factory-binding.test.ts).
    const scenes = t1.scenes.map((s: any, i: number) => ({
      ...s,
      assetId: s.shot?.assetNeed === 'screen_recording_needed' ? 'fx-gemini-video' : i % 2 === 0 ? 'fx-gemini-a' : 'fx-gemini-b',
    }));
    const r = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, {
      expectedRevision: d.json.revision,
      selectedTreatmentId: 'T1',
      scenes,
      speakers: [],
    });
    expect(r.status, r.raw).toBe(200);
    expect(r.json.missing).toEqual([]);
    expect(r.json.status).toBe('review_required');
  });

  it('apply refuses without an explicit call count, and makes no provider call', async () => {
    const before = provider.tts.length;
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: 2 });
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('FACTORY_INPUTS_REQUIRED');
    expect(r.json.speechCalls).toBe(3);
    expect(provider.tts.length).toBe(before);
    const wrong = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: 2, confirmSpeechCalls: 2 });
    expect(wrong.status).toBe(422);
    expect(provider.tts.length).toBe(before);
  });

  it('apply with the confirmed count makes one unary turn per line, stores real WAV assets with provenance', async () => {
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: 2, confirmSpeechCalls: 3 });
    expect(r.status).toBe(201);
    expect(r.json.projectId).toBeTruthy();
    expect(provider.tts.length).toBe(3);
    for (const call of provider.tts as any[]) {
      expect(call.generationConfig.responseFormat.audio.mimeType).toBe('AUDIO_WAV');
      expect(call.generationConfig.speechConfig.voiceConfig.prebuiltVoiceConfig.voiceName).toBe('Kore');
      expect(call.contents[0].parts[0].speechMetadata).toEqual({ style: 'calm and clear' });
    }
    const assets = speechAssets();
    expect(assets).toHaveLength(3);
    for (const a of assets) {
      expect(a.mimeType).toBe('audio/wav');
      expect(a.source).toMatch(/Gemini TTS \(model gemini-3\.8-flash-tts, voice Kore, language en/);
      expect(a.tags).toContain('unapproved');
      const bytes = fs.readFileSync(path.join(ASSETS_DIR, a.fileName));
      expect(bytes.subarray(0, 4).toString('ascii')).toBe('RIFF');
    }
    ids.projectId = r.json.projectId;
  });

  it('an unchanged apply reuses the project and makes no provider call', async () => {
    const before = provider.tts.length;
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: 2 });
    expect(r.status).toBe(200);
    expect(r.json.reused).toBe(true);
    expect(provider.tts.length).toBe(before);
    const g = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    expect(g.status).toBe(200);
    expect(provider.tts.length).toBe(before);
  });

  it('switching treatment reuses the clips by source unit: no new provider call', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const t2 = d.json.treatments.find((t: any) => t.id === 'T2');
    const scenes = t2.scenes.map((s: any, i: number) => ({ ...s, assetId: i % 2 === 0 ? 'fx-gemini-b' : 'fx-gemini-a' }));
    const patched = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, {
      expectedRevision: d.json.revision,
      selectedTreatmentId: 'T2',
      scenes,
      speakers: [],
    });
    expect(patched.status).toBe(200);
    const before = provider.tts.length;
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: patched.json.revision, confirmSpeechCalls: 0 });
    expect(r.status).toBe(201);
    expect(provider.tts.length).toBe(before);
    expect(speechAssets()).toHaveLength(3);
  });

  it('selective regeneration: one edited line costs one call and leaves the other clips byte-for-byte unchanged', async () => {
    const before = new Map(speechAssets().map((a: any) => [a.id, fs.readFileSync(path.join(ASSETS_DIR, a.fileName)).toString('base64')]));
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const edit = await call('PATCH', `/api/factory/drafts/${ids.draftId}/generated`, {
      expectedRevision: d.json.revision,
      edits: [{ unitId: 'L02', narration: 'Confirm the window the night before with the supplier, in writing.' }],
    });
    expect(edit.status).toBe(200);
    const before2 = provider.tts.length;
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: edit.json.revision, confirmSpeechCalls: 1 });
    expect(r.status).toBe(201);
    expect(provider.tts.length).toBe(before2 + 1);
    const after = speechAssets();
    expect(after).toHaveLength(4);
    for (const [id, data] of before) {
      const a = after.find((x: any) => x.id === id);
      expect(a).toBeTruthy();
      expect(fs.readFileSync(path.join(ASSETS_DIR, a.fileName)).toString('base64')).toBe(data);
    }
  });

  it('a provider 401 during apply fails safely: no project, no new clip, nothing left behind', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const edit = await call('PATCH', `/api/factory/drafts/${ids.draftId}/generated`, {
      expectedRevision: d.json.revision,
      edits: [{ unitId: 'L03', narration: 'Write the confirmed time on the site board for every crew.' }],
    });
    expect(edit.status).toBe(200);
    const assetsBefore = speechAssets().length;
    const filesBefore = fs.readdirSync(ASSETS_DIR).length;
    provider.failNextTts = 1;
    const r = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: edit.json.revision, confirmSpeechCalls: 1 });
    expect(r.status).toBe(401);
    expect(r.json.code).toBe('FACTORY_PROVIDER_AUTH');
    expect(r.raw).not.toContain('FIXTURE-KEY-FLOW');
    expect(speechAssets().length).toBe(assetsBefore);
    expect(fs.readdirSync(ASSETS_DIR).length).toBe(filesBefore);
  });

  it('the production budget refuses before any call once the session cap is reached', async () => {
    // Cap is 6. Used so far: 3 (first apply) + 1 (edit L02) + 1 (the 401 attempt, reserved) = 5. One turn left.
    // L03 still needs its clip from the failed attempt, so an edit to L01 needs two calls, not one.
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const edit = await call('PATCH', `/api/factory/drafts/${ids.draftId}/generated`, {
      expectedRevision: d.json.revision,
      edits: [{ unitId: 'L01', narration: 'The truck came at nine, two hours after the booked seven.' }],
    });
    expect(edit.status).toBe(200);
    const before = provider.tts.length;
    const wrongCount = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: edit.json.revision, confirmSpeechCalls: 1 });
    expect(wrongCount.status).toBe(422);
    expect(wrongCount.json.speechCalls).toBe(2);
    expect(provider.tts.length).toBe(before);
    const refused = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: edit.json.revision, confirmSpeechCalls: 2 });
    expect(refused.status).toBe(429);
    expect(refused.json.code).toBe('FACTORY_BUDGET_EXHAUSTED');
    expect(refused.json.remaining).toBe(1);
    expect(provider.tts.length).toBe(before);
  });

  it('the generated plan and draft are never sent with project folders, recordings or private files', () => {
    for (const body of provider.text as any[]) {
      const text = JSON.stringify(body);
      expect(text).not.toMatch(/data\/|output\/|\.wav"|\.mp4/);
    }
  });
});
