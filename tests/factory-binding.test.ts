type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;

const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==', 'base64');
const TEXT_MODEL = 'gemini-2.5-flash';
const TTS_MODEL = 'gemini-3.8-flash-tts';

/** LABELLED TEST DOUBLE for the Gemini REST endpoint. Counts every call. */
const provider = vi.hoisted(() => ({ text: 0, tts: 0 }));
const fetchSpy = vi.fn(async (url: string) => {
  const u = String(url);
  const json = (payload: unknown, status = 200) => ({ ok: status < 400, status, json: async () => payload });
  if (u.endsWith('/v1/chat/completions')) {
    provider.text += 1;
    return json({ choices: [{ message: { content: JSON.stringify(fixtureEducationalPlan()) }, finish_reason: 'stop' }] });
  }
  if (u.endsWith('/interactions')) {
    provider.tts += 1;
    const wav = makeWav({ seconds: 0.5 + provider.tts * 0.05 });
    return json({ status: 'completed', steps: [{ type: 'model_output', content: [{ type: 'audio', mime_type: 'audio/wav', data: b64(wav) }] }] });
  }
  throw new Error(`TEST DOUBLE: unexpected provider URL ${u}`);
});

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({
    method,
    url,
    payload: body === undefined ? undefined : JSON.stringify(body),
    headers: body === undefined ? {} : { 'content-type': 'application/json' },
  });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json, raw: res.body };
}

const SOURCE = 'Fixture (synthetic, generated by the test)';

function seedAsset(id: string, mimeType: string, fileName: string, bytes: Buffer, extra: Record<string, unknown> = {}): void {
  fs.mkdirSync(ASSETS_DIR, { recursive: true });
  fs.writeFileSync(path.join(ASSETS_DIR, fileName), bytes);
  saveAssetIndex([
    ...loadAssetIndex(),
    {
      id, name: `Fixture ${id}`, kind: 'broll', fileName, path: fileName, mimeType, sizeBytes: bytes.length,
      tags: [], status: 'active', preferred: false, source: SOURCE, license: 'Test fixture',
      addedAt: new Date().toISOString(), usedIn: [], blocked: false, ...extra,
    } as never,
  ]);
}

function setAsset(id: string, change: Record<string, unknown>): void {
  saveAssetIndex(loadAssetIndex().map((a: any) => (a.id === id ? { ...a, ...change } : a)) as never);
}

async function waitForJob(jobId: string): Promise<any> {
  for (let i = 0; i < 400; i++) {
    const r = await call('GET', `/api/factory/ai/jobs/${jobId}`);
    if (r.json.job.status !== 'running') return r.json.job;
    await new Promise((res) => setTimeout(res, 10));
  }
  throw new Error('job did not finish');
}

const ids = { draftId: '' };

