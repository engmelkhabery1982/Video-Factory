describe('asset binding and shot list (labelled provider double, fixture media)', () => {
  it('creates a generated draft; every unbound scene is missing, a recording need has a brief and no prompt', async () => {
    const created = await call('POST', '/api/factory/ai/plans', {
      profile: 'educational', format: 'landscape', brief: 'Explain why deliveries must be confirmed the night before.',
    });
    expect(created.status).toBe(202);
    const job = await waitForJob(created.json.job.id);
    expect(job.status).toBe('succeeded');
    const draft = await call('POST', `/api/factory/ai/plans/${job.id}/draft`, { format: 'landscape' });
    expect(draft.status).toBe(201);
    ids.draftId = draft.json.draftId;

    const list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    expect(list.status).toBe(200);
    const t1 = (await call('GET', `/api/factory/drafts/${ids.draftId}`)).json.treatments.find((t: any) => t.id === 'T1');
    expect(list.json.scenes.map((s: any) => s.status)).toEqual(['missing', 'missing', 'missing']);
    const recording = list.json.scenes.find((s: any) => s.assetNeed === 'screen_recording_needed');
    expect(recording.screenRecordingBrief).toMatch(/screen recording/i);
    expect(recording.prompt).toBeNull();
    const still = list.json.scenes.find((s: any) => s.assetNeed === 'image_needed');
    expect(still.prompt).toMatch(/still image/i);
    expect(still.mediaType).toBeNull();
    expect(still.source).toBeNull();
    expect(t1.scenes.length).toBe(3);
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    expect(d.json.missing.map((m: any) => m.kind).sort()).toEqual(['image', 'image', 'recording'].sort());
  });

  it('a still bound to a screen-recording need is incompatible and stops Apply before any provider call', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const scenes = d.json.treatments.find((t: any) => t.id === 'T1').scenes.map((s: any) => ({ ...s, assetId: 'fx-bind-a' }));
    const patched = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, { expectedRevision: d.json.revision, selectedTreatmentId: 'T1', scenes, speakers: [] });
    expect(patched.status, patched.raw).toBe(200);

    const list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    const rec = list.json.scenes.find((s: any) => s.assetNeed === 'screen_recording_needed');
    expect(rec.status).toBe('incompatible');
    expect(rec.reason).toMatch(/still image/i);
    expect(rec.mediaType).toBe('image');

    const preview = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(preview.json.canApply).toBe(false);
    expect(preview.json.blockers.some((b: { kind: string }) => b.kind === 'recording')).toBe(true);

    const before = provider.tts;
    const applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: patched.json.revision, confirmSpeechCalls: 3 });
    expect(applied.status).toBe(422);
    expect(applied.json.code).toBe('FACTORY_INPUTS_REQUIRED');
    expect(provider.tts).toBe(before);
  });

  it('bound supplied media: each shot shows media type, source, licence and status; Markdown carries the same data', async () => {
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const scenes = d.json.treatments.find((t: any) => t.id === 'T1').scenes.map((s: any) => ({
      ...s,
      assetId: s.shot?.assetNeed === 'screen_recording_needed' ? 'fx-bind-video' : s.shot?.assetNeed === 'image_needed' ? 'fx-bind-b' : 'fx-bind-a',
    }));
    const patched = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, { expectedRevision: d.json.revision, selectedTreatmentId: 'T1', scenes, speakers: [] });
    expect(patched.status, patched.raw).toBe(200);
    expect(patched.json.missing).toEqual([]);
    expect(patched.json.status).toBe('review_required');

    const list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    const byNeed = Object.fromEntries(list.json.scenes.map((s: any) => [s.assetNeed, s]));
    expect(byNeed.screen_recording_needed).toMatchObject({ status: 'bound', mediaType: 'video', source: SOURCE, license: 'Test fixture', boundAssetId: 'fx-bind-video' });
    expect(byNeed.image_needed).toMatchObject({ status: 'bound', mediaType: 'image', source: SOURCE, license: 'Test fixture', boundAssetId: 'fx-bind-b', prompt: expect.stringContaining('Site board photo') });
    expect(list.json.scenes.every((s: any) => s.reason === null)).toBe(true);

    const md = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list?format=md`);
    expect(md.raw).toContain('Media: video. Source: ' + SOURCE + '. Licence: Test fixture.');
    expect(md.raw).toContain('Media: image.');
    expect(md.raw).not.toContain('Blocked by:');
    expect(md.raw).toContain('Text only');
  });

  it('a bound file that changes after binding is "changed": Apply refuses with no provider call, and rebinding accepts the new bytes', async () => {
    const before = provider.tts;
    const file = path.join(ASSETS_DIR, 'fx-bind-a.png');
    fs.writeFileSync(file, Buffer.concat([PNG, Buffer.from('edited')]));

    const list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    const changed = list.json.scenes.filter((s: any) => s.boundAssetId === 'fx-bind-a');
    expect(changed.length).toBeGreaterThan(0);
    expect(changed.every((s: any) => s.status === 'changed')).toBe(true);
    expect(changed[0].reason).toMatch(/changed after it was bound/);

    const preview = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(preview.json.canApply).toBe(false);
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 3 });
    expect(applied.status).toBe(422);
    expect(applied.json.code).toBe('FACTORY_INPUTS_REQUIRED');
    expect(provider.tts).toBe(before);

    // Unbind, then bind the same asset again: the current bytes are recorded and the scene is bound.
    const unbound = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, {
      expectedRevision: d.json.revision, selectedTreatmentId: 'T1',
      scenes: d.json.treatments.find((t: any) => t.id === 'T1').scenes.map((s: any) => ({ ...s, assetId: s.assetId === 'fx-bind-a' ? null : s.assetId })),
      speakers: [],
    });
    expect(unbound.status, unbound.raw).toBe(200);
    const rebound = await call('PATCH', `/api/factory/drafts/${ids.draftId}`, {
      expectedRevision: unbound.json.revision, selectedTreatmentId: 'T1',
      scenes: unbound.json.treatments.find((t: any) => t.id === 'T1').scenes.map((s: any) => ({ ...s, assetId: s.assetId === null && s.shot?.assetNeed !== 'screen_recording_needed' && s.shot?.assetNeed !== 'image_needed' ? 'fx-bind-a' : s.assetId })),
      speakers: [],
    });
    expect(rebound.status, rebound.raw).toBe(200);
    const after = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    expect(after.json.scenes.filter((s: any) => s.boundAssetId === 'fx-bind-a').every((s: any) => s.status === 'bound')).toBe(true);
  });

  it('a blocked asset stops Apply; an asset with no licence is blocked with its reason; restoring them clears the gate', async () => {
    const before = provider.tts;
    setAsset('fx-bind-b', { blocked: true });
    let list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    expect(list.json.scenes.find((s: any) => s.boundAssetId === 'fx-bind-b').status).toBe('blocked');
    expect(list.json.scenes.find((s: any) => s.boundAssetId === 'fx-bind-b').reason).toMatch(/blocked or inactive/);
    let d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    let applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 3 });
    expect(applied.status).toBe(422);
    expect(provider.tts).toBe(before);
    setAsset('fx-bind-b', { blocked: false });

    setAsset('fx-bind-b', { license: '' });
    list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    const unlicensed = list.json.scenes.find((s: any) => s.boundAssetId === 'fx-bind-b');
    expect(unlicensed.status).toBe('blocked');
    expect(unlicensed.reason).toMatch(/no recorded source and licence/);
    d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 3 });
    expect(applied.status).toBe(422);
    expect(provider.tts).toBe(before);
    setAsset('fx-bind-b', { license: 'Test fixture' });
  });

  it('with every visual bound and current, Apply is allowed and spends exactly the confirmed count; the shot list stays bound', async () => {
    const preview = await call('GET', `/api/factory/drafts/${ids.draftId}/apply-preview`);
    expect(preview.json.canApply).toBe(true);
    expect(preview.json.speechCalls).toBe(3);
    const before = provider.tts;
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const applied = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 3 });
    expect(applied.status).toBe(201);
    expect(provider.tts - before).toBe(3);
    const list = await call('GET', `/api/factory/drafts/${ids.draftId}/shot-list`);
    expect(list.json.scenes.every((s: any) => s.status === 'bound')).toBe(true);
  });

  it('after a successful apply, a changed bound file refuses the re-apply of the same revision: nothing is reused, nothing is called', async () => {
    const before = provider.tts;
    fs.writeFileSync(path.join(ASSETS_DIR, 'fx-bind-video.mp4'), Buffer.from('FIXTURE-VIDEO-EDITED-AFTER-APPLY'));
    const d = await call('GET', `/api/factory/drafts/${ids.draftId}`);
    const again = await call('POST', `/api/factory/drafts/${ids.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 0 });
    expect(again.status).toBe(409);
    expect(again.json.code).toBe('FACTORY_SOURCE_CHANGED');
    expect(provider.tts).toBe(before);
  });
});
