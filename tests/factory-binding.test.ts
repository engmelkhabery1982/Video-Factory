/**
 * Asset binding and shot list, through the REAL registered server.
 *
 * Shows: each shot reports its media type, source, licence and status; a still is never
 * accepted for a screen-recording need; a bound file that changes after binding, or an asset
 * that is blocked or unlicensed, stops Apply BEFORE any provider call; unbinding and binding
 * again accepts the current file; the Markdown package carries the same data as the JSON.
 *
 * LABELLED TEST DOUBLES: the Gemini provider is a scripted fetch double (plan text and WAV
 * clips). The image and video files are synthetic fixtures written by this test. Nothing here
 * is owner media, a live provider result, or owner acceptance.
 */
