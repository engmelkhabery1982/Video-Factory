/** Apply a reviewed storyboard into a derived project; returns its id and first still clip. */
async function appliedProject() {
  const created = await call('POST', '/api/factory/drafts', {
    contentProfile: 'educational',
    format: 'landscape',
    channelBrandId: null,
    inputs: {
      brief: 'Fixture', script: null, audioAssetId: null, visualAssetIds: [], requestedSpeakers: undefined,
      storyboard: { version: 1, scenes: [
        { id: 's1', narration: 'Check the window.', speakerId: null, assetId: 'fx-image-a', startSec: null, endSec: null },
        { id: 's2', narration: 'Confirm the crew.', speakerId: null, assetId: 'fx-image-b', startSec: null, endSec: null },
      ] },
    },
    requestedSpeakers: [],
    referenceProjectId: null,
    visualLanguage: 'motion_explainer',
  });
  expect(created.status).toBe(201);
  const treatment = created.json.treatments[0];
  const set = await call('PATCH', `/api/factory/drafts/${created.json.draftId}`, { expectedRevision: 0, selectedTreatmentId: treatment.id, scenes: treatment.scenes, speakers: [] });
  expect(set.status).toBe(200);
  const applied = await call('POST', `/api/factory/drafts/${created.json.draftId}/apply`, { expectedRevision: set.json.revision });
  expect(applied.status).toBe(201);
  return applied.json.projectId as string;
}

async function editor(projectId: string) {
  const r = await call('GET', `/api/projects/${projectId}/editor?targetId=long`);
  expect(r.status).toBe(200);
  return r.json as { document: any; undoAvailable: boolean; redoAvailable: boolean };
}

describe('graphic clip edits on the canonical editor route (HTTP, fixture)', () => {
  let projectId = '';
  let clipId = '';
  let originalSource: { sourceAssetId: string; sourceInSec: number | null; sourceOutSec: number | null } = { sourceAssetId: '', sourceInSec: null, sourceOutSec: null };

  beforeAll(async () => {
    projectId = await appliedProject();
    const doc = await editor(projectId);
    const clip = doc.document.visualClips.find((c: any) => c.sourceAssetId);
    expect(clip).toBeTruthy();
    clipId = clip.id;
    originalSource = { sourceAssetId: clip.sourceAssetId, sourceInSec: clip.sourceInSec ?? null, sourceOutSec: clip.sourceOutSec ?? null };
  });

  const clipNow = async () => (await editor(projectId)).document.visualClips.find((c: any) => c.id === clipId);
  const save = (baseRevision: number, operations: unknown[]) => call('PATCH', `/api/projects/${projectId}/editor`, { targetId: 'long', baseRevision, operations });

  it('a graphic technique with no values is not saved: the server refuses it and the document is unchanged', async () => {
    const before = await editor(projectId);
    const plan = planTechniqueChange(await clipNow(), 'process_path', null);
    expect(plan.status).toBe('pending');
    const forced = await save(before.document.revision, [opUpdate('visualClips', clipId, { technique: 'process_path' })]);
    expect(forced.status).toBeGreaterThanOrEqual(400);
    const after = await editor(projectId);
    expect(after.document.revision).toBe(before.document.revision);
    expect((await clipNow()).sourceAssetId).toBe(originalSource.sourceAssetId);
  });

  it('a graphic longer than its clip is refused by the server and nothing is written (negative)', async () => {
    const before = await editor(projectId);
    const tooLong = buildProcessGraphic({ title: '', items: ['Book the truck', 'Confirm the crew', 'Check the window'] }, 'landscape', 6);
    const r = await save(before.document.revision, [opUpdate('visualClips', clipId, planGraphicValues('process_path', tooLong).status === 'stage' ? (planGraphicValues('process_path', tooLong) as { changes: Record<string, unknown> }).changes : {})]);
    expect(r.status).toBe(422);
    expect(r.json.code).toBe('EDITOR_INVALID_CHANGE');
    expect((await editor(projectId)).document.revision).toBe(before.document.revision);
  });

  it('complete graphic values save as one canonical update that clears the picture source', async () => {
    const before = await editor(projectId);
    // Built for the clip's own duration, exactly as the inspector does (a graphic longer than its clip is refused).
    const graphic = buildProcessGraphic({ title: '', items: ['Book the truck', 'Confirm the crew', 'Check the window'] }, 'landscape', (await clipNow()).durationSec);
    const plan = planGraphicValues('process_path', graphic);
    expect(plan.status).toBe('stage');
    const r = await save(before.document.revision, [opUpdate('visualClips', clipId, plan.status === 'stage' ? plan.changes : {})]);
    expect(r.status).toBe(200);
    expect(r.json.document.revision).toBe(before.document.revision + 1);
    expect(r.json.undoAvailable).toBe(true);
    const clip = await clipNow();
    expect(clip.technique).toBe('process_path');
    expect(clip.graphic.kind).toBe('process_path');
    expect(clip.sourceAssetId).toBeNull();
  });

  it('undo restores the picture; redo restores the graphic; both are revision-checked', async () => {
    const before = await editor(projectId);
    const undo = await call('POST', `/api/projects/${projectId}/editor/undo`, { targetId: 'long', baseRevision: before.document.revision });
    expect(undo.status).toBe(200);
    expect((await clipNow()).sourceAssetId).toBe(originalSource.sourceAssetId);
    const stale = await call('POST', `/api/projects/${projectId}/editor/redo`, { targetId: 'long', baseRevision: before.document.revision });
    expect(stale.status).toBe(409);
    const redo = await call('POST', `/api/projects/${projectId}/editor/redo`, { targetId: 'long', baseRevision: undo.json.document.revision });
    expect(redo.status).toBe(200);
    expect((await clipNow()).technique).toBe('process_path');
  });

  it('going back to a media technique without a remembered picture is refused; with the restore it saves the picture', async () => {
    const current = await clipNow();
    const refused = planTechniqueChange(current, 'still_image', null);
    expect(refused.status).toBe('refused');
    const restored = planTechniqueChange(current, 'still_image', originalSource);
    expect(restored.status).toBe('stage');
    const doc = await editor(projectId);
    const r = await save(doc.document.revision, [opUpdate('visualClips', clipId, restored.status === 'stage' ? restored.changes : {})]);
    expect(r.status).toBe(200);
    const clip = await clipNow();
    expect(clip.technique).toBe('still_image');
    expect(clip.sourceAssetId).toBe(originalSource.sourceAssetId);
    expect(clip.graphic ?? null).toBeNull();
  });

  it('a save against a stale revision is refused with 409 and nothing is written', async () => {
    const doc = await editor(projectId);
    const r = await save(doc.document.revision - 1, [opUpdate('visualClips', clipId, { technique: null, graphic: null })]);
    expect(r.status).toBe(409);
    expect(r.json.code).toBe('REVISION_CONFLICT');
    expect((await editor(projectId)).document.revision).toBe(doc.document.revision);
  });

  it('preview is reported as unavailable on this host, never as a success', async () => {
    const doc = await editor(projectId);
    const r = await call('POST', `/api/projects/${projectId}/editor/preview`, { targetId: 'long', baseRevision: doc.document.revision, range: { startSec: 0, endSec: 3 } });
    expect(r.status).toBe(501);
    expect(r.json.code).toBe('PREVIEW_UNAVAILABLE');
    expect(r.json.status).toBe('blocked');
  });
});
