/**
 * Real local speech (sam-js) through the REAL routes, with the data directory INSIDE the working directory.
 *
 * Why this file exists: the local speech adapter refuses any target outside the working directory with a 503
 * (FACTORY_SPEECH_FAILED). The matrix test runs with its data directory under the system temp folder, so its
 * script-only row is BLOCKED by that refusal. This file runs the same kind of Apply with the data directory under
 * ./data/ (an ignored folder), and asserts SUCCESS: a generated English turn is written to disk with real bytes.
 *
 * The refusal path is not success. Nothing here is mocked: sam-js is the installed pure-JavaScript engine, no network,
 * no provider. The voice is a robotic English sample voice, not a natural voice. This is engine evidence only; it makes
 * no claim about listening quality, which needs owner review.
 */
import fs from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';

const dataRoot = vi.hoisted(() => {
  const nodeFs = process.getBuiltinModule('node:fs') as typeof import('node:fs');
  const nodePath = process.getBuiltinModule('node:path') as typeof import('node:path');
  const nodeCrypto = process.getBuiltinModule('node:crypto') as typeof import('node:crypto');
  // Inside the working directory, as the local engine requires. Removed in afterAll.
  const root = nodePath.resolve(process.cwd(), 'data', `test-sam-local-${nodeCrypto.randomBytes(4).toString('hex')}`);
  nodeFs.mkdirSync(root, { recursive: true });
  process.env.BUILDTRAKE_DATA = nodePath.join(root, 'data');
  process.env.BUILDTRAKE_OUTPUT = nodePath.join(root, 'output');
  process.env.VF_PREVIEW_DISABLE = '1';
  return root;
});

import { buildServerApp } from '../apps/api/src/server.js';

type App = Awaited<ReturnType<typeof buildServerApp>>;
let app: App;
let picture: { id: string };

/** LABELLED TEST DOUBLE. A provider request fails the call. The speech engine must succeed without any provider. */
const providerCalls = vi.hoisted(() => ({ n: 0 }));
const fetchDouble = vi.fn(async (url: string) => {
  providerCalls.n += 1;
  throw new Error(`TEST DOUBLE: a provider call was not expected: ${url}`);
});

async function call(method: 'GET' | 'POST' | 'PATCH', url: string, body?: unknown) {
  const res = await app.inject({ method, url, payload: body === undefined ? undefined : JSON.stringify(body), headers: body === undefined ? {} : { 'content-type': 'application/json' } });
  let json: any = null;
  try { json = JSON.parse(res.body); } catch { json = res.body; }
  return { status: res.statusCode, json };
}

function multipart(fileName: string, content: Buffer, mime: string, fields: Record<string, string>) {
  const boundary = '----arenaSam';
  const parts: Buffer[] = [];
  for (const [name, value] of Object.entries(fields)) parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="${name}"\r\n\r\n${value}\r\n`));
  parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="${fileName}"\r\nContent-Type: ${mime}\r\n\r\n`));
  parts.push(content);
  parts.push(Buffer.from(`\r\n--${boundary}--\r\n`));
  return { headers: { 'content-type': `multipart/form-data; boundary=${boundary}` }, payload: Buffer.concat(parts) };
}

beforeAll(async () => {
  vi.stubGlobal('fetch', fetchDouble);
  app = await buildServerApp();
  await app.ready();
  const { default: sharp } = await import('sharp');
  const png = await sharp({ create: { width: 16, height: 9, channels: 3, background: '#2a6' } }).png().toBuffer();
  const res = await app.inject({ method: 'POST', url: '/api/assets', ...multipart('final.png', png, 'image/png', { name: 'sam-test-picture', kind: 'screenshot', source: 'SAM test fixture (synthetic, generated by the test)', license: 'Synthetic fixture, test only' }) });
  if (res.statusCode !== 200) throw new Error(`fixture upload failed: ${res.statusCode} ${res.body}`);
  picture = res.json().asset;
});

afterAll(async () => {
  vi.unstubAllGlobals();
  await app?.close();
  fs.rmSync(dataRoot, { recursive: true, force: true });
});

describe('local speech (sam-js) success, data directory inside the working directory', () => {
  it('the data directory is inside the working directory (the engine requirement)', () => {
    const rel = path.relative(process.cwd(), process.env.BUILDTRAKE_DATA!);
    expect(rel.startsWith('..')).toBe(false);
    expect(path.isAbsolute(rel)).toBe(false);
  });

  it('a script with generated narration: Apply succeeds, one speech turn is written with real bytes, and no provider is called', async () => {
    const script = 'The local voice reads one short English line for this test.';
    // A supplied, licensed picture for the one image shot. The narration text is the speech input.
    const r = await call('POST', '/api/factory/drafts', {
      contentProfile: 'educational', format: 'landscape', channelBrandId: null, requestedSpeakers: [], referenceProjectId: null, visualLanguage: null,
      inputs: {
        brief: '', script: null, audioAssetId: null, visualAssetIds: [picture.id],
        storyboard: { version: 1, scenes: [{ id: 's1', narration: script, speakerId: null, assetId: picture.id, startSec: null, endSec: null, locked: false }] },
        narrationMode: 'generate', textAuthority: 'storyboard', captions: false,
      },
    });
    expect(r.status).toBe(201);
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, {
      expectedRevision: r.json.revision,
      confirmSpeechCalls: 1,
    });
    expect(a.status).toBe(201);
    expect(r.json.status).toBe('review_required');
    expect(a.json.speechGenerated).toBe(1);
    expect(a.json.projectId).toBeTruthy();
    expect(providerCalls.n).toBe(0);

    // The written audio is under the isolated data directory and is not empty.
    const audio: string[] = [];
    const walk = (dir: string) => {
      for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) walk(p);
        else if (/\.(wav|mp3|ogg|flac|aac|m4a)$/i.test(e.name)) audio.push(p);
      }
    };
    walk(process.env.BUILDTRAKE_DATA!);
    expect(audio.length).toBeGreaterThan(0);
    const bytes = Math.max(...audio.map((p) => fs.statSync(p).size));
    expect(bytes).toBeGreaterThan(1000);
  });
});
