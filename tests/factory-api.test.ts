    const u03After = doc2.audioClips.find((c) => c.id === 'ac_u03')!.sourceAssetId;
    expect(u03After).not.toBe(u03Before);
    expect(doc2.audioClips.find((c) => c.id === 'ac_u03')!.speakerId).toBe('host');
