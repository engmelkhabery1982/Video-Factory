describe('post-create card edits: stale 409, reload with merge, save, reopen (real routes, real client, real page)', () => {
  it('a stale 409 keeps typed words, timing and picture on screen; reload merges the other writer\'s change; save and reopen keep everything', async () => {
    const d = await createDraft();
    await mount(d.id);
    // Another tab changes panel 2's words. The page still holds revision d.revision.
    const r1 = await otherWriter(d.id, d.revision, PANELS().map((p) => (p.id === 'p2' ? { ...p, narration: 'Second words, changed elsewhere.' } : p)));
    // This tab types: panel 1 words, its picture, its end time (a timing change, so it needs confirmation).
    await type('Post-save words for panel 1', 'Typed by me.');
    await act(async () => setValue(byLabel('Post-save picture for panel 1'), 'img-b'));
    await type('Post-save end for panel 1', '1.5');
    await act(async () => { q<HTMLInputElement>('input[aria-label="Confirm timing changes"]').click(); });
    const beforeRefusal = bytes(d.id);
    await clickBtn('post-create-save');
    await flush();
    expect(errorText()).toContain(`now revision ${r1}`);
    expect(errorText()).toContain('Your typed edits are kept');
    // Typed edits stay visible, and nothing was written by the refused save.
    expect((byLabel('Post-save words for panel 1') as HTMLTextAreaElement).value).toBe('Typed by me.');
    expect((byLabel('Post-save picture for panel 1') as HTMLSelectElement).value).toBe('img-b');
    expect((byLabel('Post-save end for panel 1') as HTMLInputElement).value).toBe('1.5');
    expect(bytes(d.id)).toBe(beforeRefusal);
    expect(q('[data-testid="post-create-reload"]')).toBeTruthy();

    // Explicit refresh: the page reloads the draft (real getDraft). Typed edits are merged with the newer storyboard.
    await act(async () => { q<HTMLButtonElement>('[data-testid="post-create-reload"]').click(); });
    await flush();
    await waitFor(() => host!.querySelector('[data-testid="post-create-note"]') !== null);
    expect(host!.querySelector('[data-testid="post-create-note"]')!.textContent).toContain(`revision ${r1}`);
    expect((byLabel('Post-save words for panel 1') as HTMLTextAreaElement).value).toBe('Typed by me.');
    expect((byLabel('Post-save words for panel 2') as HTMLTextAreaElement).value).toBe('Second words, changed elsewhere.');
    expect((byLabel('Post-save picture for panel 1') as HTMLSelectElement).value).toBe('img-b');

    // Save again on the refreshed revision. Both changes reach the server.
    await clickBtn('post-create-save');
    await flush();
    await waitFor(() => host!.querySelector('[data-testid="post-create-error"]') === null);
    const saved = (await call('GET', `/api/factory/drafts/${d.id}`)).json;
    expect(saved.revision).toBe(r1 + 1);
    const scenes = saved.intake.storyboard.scenes as any[];
    expect(scenes.find((s) => s.id === 'p1')).toMatchObject({ narration: 'Typed by me.', assetId: 'img-b', endSec: 1.5 });
    expect(scenes.find((s) => s.id === 'p2').narration).toBe('Second words, changed elsewhere.');

    // Reopen: a fresh mount of the same draft shows the saved values.
    await unmount();
    await mount(d.id);
    expect((byLabel('Post-save words for panel 1') as HTMLTextAreaElement).value).toBe('Typed by me.');
    expect(aiCalls).not.toHaveBeenCalled();
  });

  it('a lock added by another writer refuses the save with 423, names the panel, and keeps typed words and bytes', async () => {
    const d = await createDraft();
    await mount(d.id);
    // Typed here before the other writer locks panel 3.
    await type('Post-save words for panel 3', 'Words typed before the lock.');
    const r1 = await otherWriter(d.id, d.revision, PANELS().map((p) => (p.id === 'p3' ? { ...p, locked: true } : p)));
    // Save from the old revision: 409, typed words kept, nothing written.
    const beforeConflict = bytes(d.id);
    await clickBtn('post-create-save');
    await flush();
    expect(errorText()).toContain(`now revision ${r1}`);
    expect(bytes(d.id)).toBe(beforeConflict);
    // Reload: panel 3 is now locked on the server. The merge keeps our words, and the card shows the lock.
    await act(async () => { q<HTMLButtonElement>('[data-testid="post-create-reload"]').click(); });
    await flush();
    await waitFor(() => host!.querySelector('[data-testid="post-create-note"]') !== null);
    expect((byLabel('Post-save words for panel 3') as HTMLTextAreaElement).value).toBe('Words typed before the lock.');
    // Save into the lock: refused by the server with 423 and the panel named. Typed words stay; the stored draft is unchanged.
    const before = bytes(d.id);
    await clickBtn('post-create-save');
    await flush();
    expect(errorText()).toMatch(/Locked panels cannot change: p3/);
    expect(errorText()).toContain('Your typed edits are kept');
    expect((byLabel('Post-save words for panel 3') as HTMLTextAreaElement).value).toBe('Words typed before the lock.');
    expect(bytes(d.id)).toBe(before);
    expect((await call('GET', `/api/factory/drafts/${d.id}`)).json.revision).toBe(r1);
  });

  it('an overlapping timing is refused in the page before anything is sent, and the same change is refused by the server with nothing written', async () => {
    const d = await createDraft();
    await mount(d.id);
    const before = bytes(d.id);
    wire.length = 0;
    // Panel 1 now ends at 3 s, after panel 2 starts at 2 s.
    await type('Post-save end for panel 1', '3');
    await clickBtn('post-create-save');
    await flush();
    expect(errorText()).toMatch(/overlap|starts before|ends after|before the previous/i);
    expect(wire.filter((w) => w.method === 'PATCH')).toHaveLength(0);
    expect((byLabel('Post-save end for panel 1') as HTMLInputElement).value).toBe('3');
    expect(bytes(d.id)).toBe(before);

    // The same overlap, sent through the real route: refused, and the stored draft is unchanged.
    const overlapping = PANELS().map((p) => (p.id === 'p1' ? { ...p, endSec: 3 } : p));
    const r = await call('PATCH', `/api/factory/drafts/${d.id}/intake`, { expectedRevision: d.revision, storyboard: { version: 1, scenes: overlapping } });
    expect(r.status).toBe(422);
    expect(bytes(d.id)).toBe(before);
  });
});
