describe('integrated input matrix (real routes, real uploaded fixtures, no provider)', () => {
  it('topic only: the planner has nothing to plan from; the draft is blocked with the reason, and no provider is called', async () => {
    const r = await call('POST', '/api/factory/drafts', body({ brief: 'A short explainer about cranes.' }));
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('blocked');
    expect(providerCalls.n).toBe(0);
  });

  it('BLOCKED (engine) script only, no narration choice: the draft is created and Apply stops on the speech engine; not a pass', async () => {
    const r = await call('POST', '/api/factory/drafts', body({ script: 'First line of the script.\n\nSecond line.' }));
    expect(r.status).toBe(201);
    expect(r.json.status).toBe('review_required');
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    // The local speech engine is not available for this fixture. Apply refuses with the reason; no project is created.
    expect(a.status).toBe(503);
    expect(a.json.code).toBe('FACTORY_SPEECH_FAILED');
    expect(a.json.projectId).toBeUndefined();
    expect(providerCalls.n).toBe(0);
  });

  it('pictures only, silent: review_required, one shot per picture, Apply creates a project with zero speech and zero audio clips', async () => {
    const r = await call('POST', '/api/factory/drafts', body({ visualAssetIds: [PNG_A.id, PNG_B.id], storyboard: { version: 1, scenes: [panel('s1', '', PNG_A.id), panel('s2', '', PNG_B.id)] }, narrationMode: 'none', captions: false }));
    expect(r.json.status).toBe('review_required');
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    expect(a.json.speechGenerated).toBe(0);
    expect(readEditorState(a.json.projectId, 'long')?.document.audioClips.length).toBe(0);
    expect(providerCalls.n).toBe(0);
  });

  it('a silent text storyboard and an image storyboard (JPEG and WebP panels, no words): both apply with zero speech', async () => {
    const text = await call('POST', '/api/factory/drafts', body({ storyboard: { version: 1, scenes: [panel('t1', '', null), panel('t2', '', PNG_A.id)] }, narrationMode: 'none', captions: false }));
    const image = await call('POST', '/api/factory/drafts', body({ visualAssetIds: [JPG.id, WEBP.id], storyboard: { version: 1, scenes: [panel('i1', '', JPG.id), panel('i2', '', WEBP.id)] }, narrationMode: 'none', captions: false }));
    expect(text.json.status).toBe('review_required');
    expect(image.json.status).toBe('review_required');
    for (const d of [text.json, image.json]) {
      const a = await call('POST', `/api/factory/drafts/${d.draftId}/apply`, { expectedRevision: d.revision, confirmSpeechCalls: 0 });
      expect(a.status).toBe(201);
      expect(a.json.speechGenerated).toBe(0);
    }
  });

  it('supplied video WITH audio plus supplied narration audio: no speech is generated and the supplied audio is used as it is', async () => {
    const r = await call('POST', '/api/factory/drafts', body({
      script: 'Supplied narration line.', audioAssetId: WAV.id, visualAssetIds: [VID_AUDIO.id],
      storyboard: { version: 1, scenes: [panel('v1', 'Supplied narration line.', VID_AUDIO.id)] }, narrationMode: 'supplied', captions: false,
    }));
    expect(r.status).toBe(201);
    expect(r.json.status).not.toBe('blocked');
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    expect(a.json.speechGenerated).toBe(0);
    expect(providerCalls.n).toBe(0);
  });

  it('video WITHOUT audio, narration none: applies with zero speech and zero audio clips; the video stays silent', async () => {
    const r = await call('POST', '/api/factory/drafts', body({ visualAssetIds: [VID_SILENT.id], storyboard: { version: 1, scenes: [panel('x1', '', VID_SILENT.id)] }, narrationMode: 'none', captions: false }));
    expect(r.json.status).toBe('review_required');
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    expect(readEditorState(a.json.projectId, 'long')?.document.audioClips.length).toBe(0);
  });

  it('a silent video shorter than the scene it fills is refused by name at Apply, and nothing is created', async () => {
    const r = await call('POST', '/api/factory/drafts', body({ visualAssetIds: [VID_SHORT.id], storyboard: { version: 1, scenes: [panel('y1', '', VID_SHORT.id)] }, narrationMode: 'none', captions: false }));
    const a = await call('POST', `/api/factory/drafts/${r.json.draftId}/apply`, { expectedRevision: r.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(422);
    expect(a.json.code).toBe('FACTORY_ASSET_INVALID');
    expect(a.json.error).toMatch(/shorter/);
    expect(a.json.projectId).toBeUndefined();
  });

  it('mixed references: a style reference is attached but never becomes footage; only the final picture is a shot', async () => {
    const d = await call('POST', '/api/factory/drafts', body({ visualAssetIds: [PNG_A.id, PNG_STYLE.id], storyboard: { version: 1, scenes: [panel('m1', '', PNG_A.id)] }, narrationMode: 'none', captions: false }));
    expect(d.status).toBe(201);
    const set = await call('PATCH', `/api/factory/drafts/${d.json.draftId}/intake`, { expectedRevision: d.json.revision, visualRoles: { [PNG_A.id]: 'final_shot', [PNG_STYLE.id]: 'style_reference' } });
    expect(set.status).toBe(200);
    const a = await call('POST', `/api/factory/drafts/${d.json.draftId}/apply`, { expectedRevision: set.json.revision, confirmSpeechCalls: 0 });
    expect(a.status).toBe(201);
    const doc = readEditorState(a.json.projectId, 'long')?.document as any;
    // Footage is the visual clips. The style reference must not be among them, and it is not an asset of the project.
    const footage = JSON.stringify(doc.visualClips ?? []);
    expect(footage).toContain(PNG_A.id);
    expect(footage).not.toContain(PNG_STYLE.id);
    expect(JSON.stringify(doc.assets ?? {})).not.toContain(PNG_STYLE.id);
  });

  it('script and storyboard text that differ, narration supplied and no authority chosen: Apply refuses with a named conflict; nothing written; no provider call', async () => {
    const d = await call('POST', '/api/factory/drafts', body({ script: 'The approved script says one thing.', visualAssetIds: [PNG_A.id], storyboard: { version: 1, scenes: [panel('c1', 'The storyboard says another.', PNG_A.id)] }, narrationMode: 'supplied', captions: false }));
    expect(d.status).toBe(201);
    expect(d.json.status).toBe('blocked');
    const draftFile = path.join(process.env.BUILDTRAKE_DATA!, 'factory', 'drafts', `${d.json.draftId}.json`);
    const before = fs.readFileSync(draftFile, 'utf8');
    const apply = await call('POST', `/api/factory/drafts/${d.json.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 0 });
    expect(apply.status).toBe(422);
    expect(apply.json.code).toBe('FACTORY_INPUTS_REQUIRED');
    expect(apply.json.missing.map((m: { kind: string }) => m.kind)).toEqual(expect.arrayContaining(['conflict']));
    expect(apply.json.projectId).toBeUndefined();
    expect(fs.readFileSync(draftFile, 'utf8')).toBe(before);
    expect(providerCalls.n).toBe(0);
  });

  it('an applied project is a snapshot: structural edits after Create change the draft, not the project; a newer revision applies to a new project', async () => {
    const d = await call('POST', '/api/factory/drafts', body({ visualAssetIds: [PNG_A.id, PNG_B.id], storyboard: { version: 1, scenes: [panel('z1', '', PNG_A.id), panel('z2', '', PNG_B.id)] }, narrationMode: 'none', captions: false }));
    const first = await call('POST', `/api/factory/drafts/${d.json.draftId}/apply`, { expectedRevision: d.json.revision, confirmSpeechCalls: 0 });
    const snapshot = JSON.stringify(readEditorState(first.json.projectId, 'long'));
    const cur = await call('GET', `/api/factory/drafts/${d.json.draftId}`);
    const edit = await call('PATCH', `/api/factory/drafts/${d.json.draftId}/intake`, { expectedRevision: cur.json.revision, storyboard: { version: 1, scenes: [panel('z2', '', PNG_B.id), panel('z3', '', PNG_A.id)] } });
    expect(edit.status).toBe(200);
    expect(JSON.stringify(readEditorState(first.json.projectId, 'long'))).toBe(snapshot);
    const second = await call('POST', `/api/factory/drafts/${d.json.draftId}/apply`, { expectedRevision: edit.json.revision, confirmSpeechCalls: 0 });
    expect(second.status).toBe(201);
    expect(second.json.projectId).not.toBe(first.json.projectId);
  });

  // BLOCKED, SKIPPED ON PURPOSE: the zero-audio export render needs the Remotion render engine and a browser.
  // This sandbox has neither installed, and none was requested. Vitest reports this as skipped, never as passed.
  it.skip('BLOCKED (engine): zero-audio export render needs the Remotion render engine and a browser; not run here, owner-host evidence is separate', () => {});
});

